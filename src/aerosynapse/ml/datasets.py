r"""Parameterised-PDE dataset generators built on the Phase 1 solvers (spec Section 15 dataset card).

``convdiff_operator_dataset``: operator :math:`\mathcal G:(u_0, Pe)\mapsto u(\cdot, T)` for periodic
conv-diff. Inputs are random smooth periodic fields (truncated Fourier series with decaying spectrum).
Outputs come from the FV van Leer solver at resolution ``n``. The *numerical uncertainty* of every
sample is measured against the exact spectral solution :math:`\hat u_k(T)=\hat u_k(0)e^{-(2\pi i k v +
D(2\pi k)^2)T}` and stored.

``poisson2d_operator_dataset``: :math:`f\mapsto u` for :math:`-\Delta u=f` with zero Dirichlet data
(five-point FD, one sparse LU reused for all samples).
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field

import numpy as np
import scipy.sparse.linalg as spla
from numpy.typing import NDArray

from aerosynapse.numerics.convdiff import solve_convdiff_fv
from aerosynapse.numerics.heat import laplacian_2d_dirichlet

FloatArr = NDArray[np.float64]


@dataclass
class OperatorDataset:
    name: str
    inputs: FloatArr  # (N, C, *grid)
    outputs: FloatArr  # (N, 1, *grid)
    params: FloatArr  # (N, P)
    grid: FloatArr  # coordinates (1D) or (2, ny, nx)
    numerical_error: FloatArr  # per-sample max-norm discretisation error estimate
    card: dict[str, str] = field(default_factory=dict)

    def subset(self, idx: NDArray[np.int64]) -> OperatorDataset:
        return OperatorDataset(
            self.name,
            self.inputs[idx],
            self.outputs[idx],
            self.params[idx],
            self.grid,
            self.numerical_error[idx],
            self.card,
        )

    def hashes(self) -> list[str]:
        return [hashlib.sha1(np.ascontiguousarray(a).tobytes()).hexdigest() for a in self.inputs]


def random_periodic_field(n: int, rng: np.random.Generator, k_max: int = 4, decay: float = 2.0) -> FloatArr:
    x = np.arange(n) / n
    u = np.zeros(n)
    for k in range(1, k_max + 1):
        a, b = rng.normal(size=2) / k**decay
        u += a * np.cos(2 * np.pi * k * x) + b * np.sin(2 * np.pi * k * x)
    return np.asarray(u + 1.0)


def spectral_exact(u0_fn_coeffs: tuple[FloatArr, FloatArr], x: FloatArr, v: float, D: float, T: float) -> FloatArr:
    a, b = u0_fn_coeffs
    out = np.full_like(x, 1.0)
    for k in range(1, len(a) + 1):
        w = 2 * np.pi * k
        damp = np.exp(-D * w**2 * T)
        ph = w * (x - v * T)
        out += damp * (a[k - 1] * np.cos(ph) + b[k - 1] * np.sin(ph))
    return out


def convdiff_operator_dataset(
    n_samples: int,
    n: int = 64,
    pe_range: tuple[float, float] = (5.0, 50.0),
    T: float = 0.5,
    k_max: int = 4,
    decay: float = 2.0,
    seed: int = 0,
    log_uniform: bool = True,
) -> OperatorDataset:
    rng = np.random.default_rng(seed)
    X, Y, Pp, err = [], [], [], []
    xc = (np.arange(n) + 0.5) / n
    for _ in range(n_samples):
        a = rng.normal(size=k_max) / np.arange(1, k_max + 1) ** decay
        b = rng.normal(size=k_max) / np.arange(1, k_max + 1) ** decay
        lo, hi = pe_range
        pe = float(np.exp(rng.uniform(np.log(lo), np.log(hi)))) if log_uniform else float(rng.uniform(lo, hi))
        D = 1.0 / pe

        def u0(x: FloatArr, a: FloatArr = a, b: FloatArr = b) -> FloatArr:
            return spectral_exact((a, b), x, 1.0, 0.0, 0.0)

        r = solve_convdiff_fv(0, 1, n, 1.0, D, u0, T, scheme="vanleer", cfl=0.4)
        ex = spectral_exact((a, b), r.x, 1.0, D, T)
        X.append(np.stack([u0(xc), np.full(n, np.log10(pe))]))
        Y.append(r.u[None])
        Pp.append([pe])
        err.append(float(np.abs(r.u - ex).max()))
    card = {
        "source": "generated by aerosynapse.numerics.convdiff (FV van Leer, SSP-RK3) — synthetic, no external data",
        "licence": "same as the repository (Apache-2.0)",
        "physical_system": "periodic 1D convection-diffusion, v = 1, D = 1/Pe, final time T",
        "format": "inputs (N, 2, n): [u0, log10 Pe broadcast]; outputs (N, 1, n): u(x, T) at cell centres",
        "units": "non-dimensional",
        "split": "by parameter range (in-distribution vs out-of-distribution Pe) and by input-spectrum",
        "leakage_risks": "duplicate fields across splits (checked by SHA-1 of inputs)",
        "limitations": "smooth inputs only (k <= k_max); FV discretisation error stored per sample",
    }
    return OperatorDataset("convdiff_operator", np.array(X), np.array(Y), np.array(Pp), xc, np.array(err), card)


def poisson2d_operator_dataset(n_samples: int, n: int = 32, k_max: int = 3, seed: int = 0) -> OperatorDataset:
    rng = np.random.default_rng(seed)
    h = 1.0 / n
    L = laplacian_2d_dirichlet(n, n, h, h)
    lu = spla.splu((-L).tocsc())
    xs = np.linspace(0, 1, n + 1)
    Xg, Yg = np.meshgrid(xs, xs)
    F, U = [], []
    for _ in range(n_samples):
        f = np.zeros_like(Xg)
        for i in range(1, k_max + 1):
            for j in range(1, k_max + 1):
                f += (
                    rng.normal()
                    / (i + j)
                    * np.sin(np.pi * i * Xg)
                    * np.sin(np.pi * j * Yg)
                    * np.pi**2
                    * (i * i + j * j)
                )
        u = np.zeros_like(f)
        u[1:-1, 1:-1] = lu.solve(f[1:-1, 1:-1].ravel()).reshape(n - 1, n - 1)
        F.append(f[None])
        U.append(u[None])
    card = {
        "source": "five-point FD Poisson (aerosynapse.numerics) — synthetic",
        "licence": "Apache-2.0",
        "physical_system": "-lap u = f on the unit square, u = 0 on the boundary",
        "format": "inputs (N,1,n+1,n+1) f; outputs (N,1,n+1,n+1) u",
        "units": "non-dimensional",
        "split": "random",
        "leakage_risks": "none beyond duplicates (checked)",
        "limitations": "band-limited sources; O(h^2) FD error",
    }
    return OperatorDataset(
        "poisson2d_operator",
        np.array(F),
        np.array(U),
        np.zeros((n_samples, 0)),
        np.stack([Xg, Yg]),
        np.full(n_samples, np.nan),
        card,
    )


def check_leakage(a: OperatorDataset, b: OperatorDataset) -> int:
    """Number of identical input samples shared between two splits (must be 0)."""
    return len(set(a.hashes()) & set(b.hashes()))
