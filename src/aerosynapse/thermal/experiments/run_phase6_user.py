"""Every Phase 6 step on YOUR conditions, one config: 6.1 scaling -> 6.2 uncertainty -> 6.3 extrapolation and validity
-> 6.4 sensitivity -> 6.5 training diagnostics -> 6.6 physical validation (2D) -> 6.6b UQ / extrapolation / diagnostics
of the 2D networks -> 6.7 cost (training, inference, hardware, break-even) -> the Phase 6 gate.

    python experiments/run_phase6_user.py [--config configs/pinn/user_phase6.yaml] [--tag mine] [--profile smoke]
                                          [--steps 6.1,6.2,6.3,6.4,6.5,6.6,6.6b,6.7,gate] [--set key=value ...]

Each step runs as its own process (python -m aerosynapse.thermal.experiments.p6_*), logs to results_<step>_<tag>.log, and writes its results,
table and figures to results/p6_*_<tag>/. Afterwards results/phase6_user_<tag>/summary.md collects the main numbers
of every step (with the physics conditions used). 6.3 evaluates the members of the 6.2 run with the same tag.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from aerosynapse.thermal.pinn import spec as SP
from aerosynapse.thermal.utils.experiment import ROOT

STEPS = {
    "6.1": ("aerosynapse.thermal.experiments.p6_1_scaling", "p6_1_scaling"),
    "6.2": ("aerosynapse.thermal.experiments.p6_2_uq", "p6_2_uq"),
    "6.3": ("aerosynapse.thermal.experiments.p6_3_extrapolation", "p6_3_extrapolation"),
    "6.4": ("aerosynapse.thermal.experiments.p6_4_sensitivity", "p6_4_sensitivity"),
    "6.5": ("aerosynapse.thermal.experiments.p6_5_diagnostics", "p6_5_diagnostics"),
    "6.6": ("aerosynapse.thermal.experiments.p6_6_validation", "p6_6_validation"),
    "6.6b": ("aerosynapse.thermal.experiments.p6_6b_2d", "p6_6b_2d"),
    "6.7": ("aerosynapse.thermal.experiments.p6_7_cost", "p6_7_cost"),
    "gate": ("aerosynapse.thermal.experiments.p6_gate", "p6_gate"),
}


def run_step(step: str, a) -> float:
    mod, _ = STEPS[step]
    cmd = [sys.executable, "-m", mod, "--config", a.config, "--tag", a.tag, "--profile", a.profile]
    for s in a.sets:
        cmd += ["--set", s]
    log = ROOT / f"results_{step.replace('.', '_')}_{a.tag}.log"
    t0 = time.perf_counter()
    print(f"[{step}] {' '.join(cmd[1:])}  (log {log.name})", flush=True)
    with open(log, "w", encoding="utf-8") as f:
        r = subprocess.run(
            cmd,
            cwd=ROOT,
            stdout=f,
            stderr=subprocess.STDOUT,
            env={**__import__("os").environ, "PYTHONIOENCODING": "utf-8"},
        )
    if r.returncode != 0:
        raise SystemExit(f"step {step} failed (exit {r.returncode}); see {log}")
    return time.perf_counter() - t0


def _metrics(prefix: str, tag: str) -> dict | None:
    f = ROOT / "results" / f"{prefix}_{tag}" / "metrics.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else None


def summary(a, spec: dict, walls: dict) -> Path:
    L = [
        f"# Phase 6 on your conditions — `{a.tag}` (auto-generated by experiments/run_phase6_user.py)",
        "",
        f"Config: `{a.config}` (profile {a.profile}). Verification only: truths are analytic (1D) or the verified FV solver (cavity).",
        "",
        "Physics conditions:",
        "",
    ]
    for p in ("A_steady", "B_slab"):
        c = spec["problems"][p]
        L.append(f"- {p}: {c['conditions']}" + (f", T = {c['T']}" if "T" in c and p != "A_steady" else ""))
    L += ["", "Wall time per step: " + ", ".join(f"{k} {v:.0f} s" for k, v in walls.items()), ""]
    m1 = _metrics("p6_1_scaling", a.tag)
    if m1:
        L += ["## 6.1 scaling", ""]
        for prob, fits in m1["fits"].items():
            base = [r["rel_l2"] for r in m1["runs"] if r["problem"] == prob and r["factor"] == "base"]
            ff = "; ".join(
                f"{k}: {f['best']} {f['exponent']:+.2f}" + ("" if f.get("resolved", True) else " (unresolved)")
                for k, f in fits.items()
            )
            eq = [r for r in m1["equal_error"][prob] if r["pinn"] and r["fd"]]
            eqt = (
                f"; at target {eq[-1]['target']:g} PINN {eq[-1]['pinn']['wall_s']:.0f} s vs FD {1e3 * eq[-1]['fd']['wall_s']:.3g} ms"
                if eq
                else "; no target reached by the PINN"
            )
            L.append(
                f"- {prob} ({m1['problems'][prob]['value']:g}): base rel L2 median {np.median(base):.3g}; {ff}{eqt}"
            )
        L.append("")
    m2 = _metrics("p6_2_uq", a.tag)
    if m2:
        L += ["## 6.2 uncertainty (test values inside the range)", ""]
        for prob, an in m2["analysis"].items():
            for k, r in an["methods"].items():
                L.append(
                    f"- {prob} {k}: rel L2 {r['rel_l2']:.3g}, dispersion {r['dispersion']:.3g}, 95 % coverage {100 * r['coverage']['0.95']:.0f} %, conformal 95 % {100 * r['conformal']['0.05']['test_coverage']:.0f} %"
                )
        L.append("")
    m3 = _metrics("p6_3_extrapolation", a.tag)
    if m3:
        L += ["## 6.3 extrapolation and validity", ""]
        for prob, r in (m3.get("parametric") or {}).items():
            d, e = np.asarray(r["distance"]), np.asarray(r["values"]["rel_l2"])
            best = max(((k, s["spearman"]) for k, s in r["scores"].items() if k != "distance"), key=lambda z: z[1])
            L.append(
                f"- {prob}: rel L2 inside median {np.median(e[d == 0]):.3g}, at > 0.5 decades outside median {np.median(e[d > 0.5]):.3g}; best indicator {best[0]} (Spearman {best[1]:.2f})"
            )
        cav = m3.get("cavity")
        if cav:
            from aerosynapse.thermal.experiments.p6_3_extrapolation import _bracket

            parts = []
            for n, g in cav["grids"].items():
                b = _bracket(g["records"])
                parts.append(
                    f"N {n}: stable at Re {b[0]:g}, unstable at Re {b[1]:g}" if b else f"N {n}: stable over the ladder"
                )
            L.append("- cavity (labelled beyond laminar; the Re ladder only brackets the change): " + "; ".join(parts))
        L.append("")
    m4 = _metrics("p6_4_sensitivity", a.tag)
    if m4:
        L += ["## 6.4 global sensitivity (total indices ST: solver / PINN ensemble)", ""]
        for case, c in m4["cases"].items():
            L.append(
                f"- {case}: "
                + "; ".join(
                    f"{k} {c['solver']['ST'][i]:.2f} / {c['pinn']['ensemble']['ST'][i]:.2f}"
                    for i, k in enumerate(("Re", "Pr", "Bi"))
                )
                + f"; PINN QoI median rel. error {c['paired']['rel_err_median']:.3g}"
            )
        L.append("")
    m5 = _metrics("p6_5_diagnostics", a.tag)
    if m5 and m5.get("cases"):
        L += ["## 6.5 training diagnostics (final relative L2; NTK effective rank at initialisation)", ""]
        for r in m5["cases"]:
            nt = r.get("ntk") or [{}]
            L.append(
                f"- {r['case']} / {r['variant']}: rel L2 {r['rel_l2'][-1]:.3g}; NTK eff. rank {nt[0].get('effective_rank', float('nan')):.3g}"
            )
        L.append("")
    m6 = _metrics("p6_6_validation", a.tag)
    if m6 and m6.get("analysis"):
        an = m6["analysis"]
        L += ["## 6.6 physical validation (2D)", ""]
        for e in an.get("graetz", []):
            L.append(
                f"- Graetz Pe {e['Pe']:g} (Re {e['Re']:g}, Pr {e['Pr']:g}): local Nu {e['Nu_local_station']:.4g} vs series {e['series_local_station']:.4g} at x = {e['x_station']:.3g} H "
                f"(median |dev| {100 * e['dev_local_median']:.2g} %)"
            )
        for e in an.get("natural", {}).values():
            dv = f", de Vahl Davis {e['dVD']:.4g}" if "dVD" in e else ""
            L.append(
                f"- cavity Pr {e['Pr']:g} Ra {e['Ra']:.0e}: Nu {e['best']:.4g} vs Berkovsky–Polevikov {e['BP']:.4g}{dv}"
            )
        L.append("")
    m6b = _metrics("p6_6b_2d", a.tag)
    if m6b and m6b.get("analysis"):
        L += ["## 6.6b 2D networks: UQ and extrapolation", ""]
        for case, an in m6b["analysis"].items():
            parts = []
            if "uq" in an:
                u = an["uq"]
                parts.append(
                    f"median QoI error {u['rel_err_median']:.3g}, 90 % coverage {u['gaussian']['coverage'].get('0.9', float('nan')):.2f} "
                    f"(conformal {u['conformal']['coverage_mean']:.2f})"
                )
            if "extrapolation" in an:
                b = an["extrapolation"]["by_distance"]
                parts.append(
                    f"error {b[0]['rel_err_median']:.3g} inside -> {b[-1]['rel_err_median']:.3g} at {b[-1]['d']:g} decades"
                )
            L.append(f"- {case}: " + "; ".join(parts))
        L.append("")
    m7 = _metrics("p6_7_cost", a.tag)
    if m7 and m7.get("analysis"):
        L += ["## 6.7 cost (break-even queries vs the solver)", ""]
        for case, c in m7["analysis"].items():
            if case.startswith("_") or c.get("solver_s") is None or c.get("pinn_query_ensemble_s") is None:
                continue
            nb = c.get("break_even_ensemble")
            L.append(
                f"- {case}: offline {c['offline_ensemble_s']:.0f} s, PINN {c['pinn_query_ensemble_s']:.3g} s / query vs solver "
                f"{c['solver_s']:.3g} s; break-even {'never' if nb is None else f'{nb:,.0f} queries'}"
            )
        L.append("")
    mg = _metrics("p6_gate", a.tag)
    if mg and mg.get("checklist"):
        L += ["## Phase 6 gate", ""]
        L += [f"- [{it['status']}] {it['item']}" for it in mg["checklist"]]
        L.append("")
    L += ["Full tables: " + ", ".join(f"results/{STEPS[s][1]}_{a.tag}/" for s in STEPS) + "."]
    out = ROOT / "results" / f"phase6_user_{a.tag}" / "summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/pinn/user_phase6.yaml")
    ap.add_argument("--tag", default="mine")
    ap.add_argument("--profile", default="smoke")
    ap.add_argument("--steps", default="6.1,6.2,6.3")
    ap.add_argument("--set", dest="sets", action="append", default=[])
    ap.add_argument("--summary-only", action="store_true")
    a = ap.parse_args()
    if a.tag == "default":
        raise SystemExit("--tag default is reserved for the default case (docs/); choose another tag")
    spec = SP.load_spec(a.config, a.profile, SP.parse_set(a.sets))  # validates the whole config before any run
    walls = {}
    wfile = ROOT / "results" / f"phase6_user_{a.tag}" / "walls.json"
    if a.summary_only and wfile.exists():
        walls = json.loads(wfile.read_text(encoding="utf-8"))
    if not a.summary_only:
        for s in [x.strip() for x in a.steps.split(",") if x.strip()]:
            if s not in STEPS:
                raise SystemExit(f"unknown step {s!r}; choose from {list(STEPS)}")
            walls[s] = run_step(s, a)
            wfile.parent.mkdir(parents=True, exist_ok=True)
            wfile.write_text(json.dumps(walls, indent=2), encoding="utf-8")
    print(f"wrote {summary(a, spec, walls)}")


if __name__ == "__main__":
    main()
