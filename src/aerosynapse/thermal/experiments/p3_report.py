"""Failure-mode table for Phase 3. Every claim is a measurement; diagnosis wording depends on what was measured.

Rules (so the table cannot assert a mechanism the data contradict):
* error vs parameter: "grows with the parameter" only if Spearman >= 0.5, "decreases" if <= -0.5, otherwise "no monotone trend";
* stalled optimisation: runs with rel L2 > 0.5 are checked against their logged loss (first vs last logged total);
* loss imbalance: reported as explanatory only if |Spearman(imbalance, error)| >= 0.5;
* spectral bias: reported as supported only if the median share of error energy above k_cut is >= 0.1.
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr


def _log_losses(run_dir: Path) -> tuple[float, float] | None:
    f = run_dir / "log.csv"
    if not f.exists():
        return None
    rows = list(csv.DictReader(open(f, encoding="utf-8")))
    return (float(rows[0]["total"]), float(rows[-1]["total"])) if rows else None


def _rho(a: list[float], b: list[float]) -> float:
    if len(a) < 3 or len(set(a)) < 2 or len(set(b)) < 2:  # rank correlation undefined for constant input
        return float("nan")
    return float(spearmanr(a, b).statistic)


def failure_table(
    recs: list[dict], studies: dict, spec: dict, path: Path, tag: str, runs_dir: Path | None = None
) -> list[str]:
    tgt = spec["evaluation"]["target_rel_l2"]
    n, t = spec["network"], spec["training"]
    L = [
        f"# Phase 3 failure-mode table — `{tag}` (auto-generated by experiments/p3_report.py from results/p3_pinn1d_{tag}/metrics.json and run logs)",
        "",
        f"Acceptance target: relative L2 < {tgt:g}. Network {n['depth']}x{n['width']} {n['activation']}, Adam {t['adam']['epochs']} + "
        f"L-BFGS {t['lbfgs']['iterations']}, {spec['sampling']['n_pde']} PDE points, profile `{spec['profile']}`.",
        "",
        "## Per-run results",
        "",
        "| Problem | Parameter | rel L2 | L∞ | rel H¹ | meets target | FD rel L2 | Chebyshev rel L2 | grad imbalance | train s |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(recs, key=lambda q: (q["problem"], q["value"])):
        rs = r["reference_solvers"]
        L.append(
            f"| {r['problem']} | {r['parameter']}={r['value']:g} | {r['rel_l2']:.3e} | {r['linf']:.3e} | {r['rel_h1']:.3e} | "
            f"{'yes' if r['meets_target'] else '**no**'} | {rs['fd']['rel_l2']:.2e} | {rs['spectral']['rel_l2']:.2e} | "
            f"{r['grad_imbalance_max_over_min']:.1e} | {r['wall_s']:.0f} |"
        )
    L += [
        "",
        "## Failure modes observed (measurements; diagnosis worded from the evidence)",
        "",
        "| Mode | Evidence in this run | What the evidence supports | Candidate fix (Phase 4) |",
        "|---|---|---|---|",
    ]
    names = list(dict.fromkeys(r["problem"] for r in recs))
    # (F1) error vs parameter
    for name in names:
        sel = sorted((r for r in recs if r["problem"] == name), key=lambda q: q["value"])
        if len(sel) < 2:
            continue
        e, li = [q["rel_l2"] for q in sel], [q["linf"] for q in sel]
        rho = _rho([q["value"] for q in sel], e)
        worst = max(sel, key=lambda q: q["rel_l2"])
        fail = [f"{q['parameter']}={q['value']:g}" for q in sel if not q["meets_target"]]
        if rho >= 0.5:
            sup = (
                "error grows with the parameter, consistent with sharper solution features (boundary layer / fast transient) being "
                "harder to fit; not proven to be the cause"
            )
        elif rho <= -0.5:
            sup = (
                f"error DECREASES with the parameter (worst at {worst['parameter']}={worst['value']:g}); sharpness is not what limits accuracy here. "
                f"Absolute L∞ spans only {min(li):.2e}–{max(li):.2e}, so the larger relative error at low parameter reflects a smaller reference norm "
                "and generic under-training of the transient problem"
            )
        else:
            sup = "no monotone trend with the parameter"
        L.append(
            f"| Error vs {sel[0]['parameter']} ({name}) | rel L2 {min(e):.2e}–{max(e):.2e}; worst at {worst['parameter']}={worst['value']:g}; "
            f"Spearman = {rho:.2f}; misses target at: {', '.join(fail) if fail else 'none'} | {sup} | adaptive weights, Fourier features, RAR, hard constraints |"
        )
    # (F2) stalled optimisation / wrong solution
    wrong = [r for r in recs if r["rel_l2"] > 0.5]
    for r in sorted(wrong, key=lambda q: (q["problem"], q["value"])):
        ll = _log_losses(runs_dir / f"{r['problem']}_{r['value']:g}") if runs_dir else None
        fl = r["final_losses"]
        ev = (
            f"rel L2 = {r['rel_l2']:.2f}, L∞ = {r['linf']:.2f}; final loss terms pde {fl.get('pde', float('nan')):.2e}, "
            f"bc {fl.get('bc_left', float('nan')):.2e}/{fl.get('bc_right', float('nan')):.2e}"
        )
        if ll:
            ev += f"; logged total loss {ll[0]:.2e} → {ll[1]:.2e} (reduction ×{ll[0] / ll[1]:.1f})"
            sp_err = r["reference_solvers"]["spectral"]["rel_l2"]
            solvable = (
                f"while the Chebyshev solver solves this problem to {sp_err:.1e}: an optimisation failure, not a lack of representability"
                if sp_err < tgt
                else f"(the Chebyshev reference is itself under-resolved here, rel L2 {sp_err:.1e}, so solvability is not shown by it; "
                "raise evaluation.reference_solvers.spectral_N)"
            )
            sup = (
                f"loss did not decrease substantially (optimiser stalled on a high plateau) {solvable}"
                if ll[0] / ll[1] < 50
                else "loss decreased strongly but the solution is still wrong: the loss does not identify the solution (ill-posed weighting or insufficient points)"
            )
        else:
            sup = "per-run log not available; stalled vs mis-weighted not distinguishable from these data"
        L.append(
            f"| Wrong-solution convergence ({r['problem']}, {r['parameter']}={r['value']:g}) | {ev} | {sup} | adaptive weights, Fourier features, RAR, hard constraints, curriculum in Pe |"
        )
    # (F3) imbalance
    imb = [(r["grad_imbalance_max_over_min"], r["rel_l2"]) for r in recs if r["grad_imbalance_max_over_min"]]
    if len(imb) >= 3:
        rho = _rho([a for a, _ in imb], [b for _, b in imb])
        sup = (
            "larger gradient-norm imbalance goes with larger error (consistent with competing loss terms)"
            if rho >= 0.5
            else "no monotone relation between raw gradient-norm imbalance and error in this run: imbalance (as measured) does not explain the error ranking"
            if abs(rho) < 0.5
            else "larger imbalance goes with SMALLER error: imbalance (as measured) is not a failure driver here"
        )
        L.append(
            f"| Loss imbalance | gradient-norm ratio max/min over terms {min(a for a, _ in imb):.1e}–{max(a for a, _ in imb):.1e}; "
            f"Spearman(imbalance, error) = {rho:.2f} | {sup} | learning-rate annealing, GradNorm, NTK weights |"
        )
    if "loss_weights" in studies:
        s = studies["loss_weights"]
        rows = "; ".join(f"w_bc={q['bc_weight']:g}: {q['rel_l2']:.2e}" for q in s["runs"])
        best = min(s["runs"], key=lambda q: q["rel_l2"])
        spread = max(q["rel_l2"] for q in s["runs"]) / max(min(q["rel_l2"] for q in s["runs"]), 1e-300)
        L.append(
            f"| Loss-weight sensitivity ({s['problem']}, {s['parameter']}={s['value']:g}) | {rows}; best w_bc = {best['bc_weight']:g} | "
            f"changing only the boundary weight changes the error by ×{spread:.1f}; the best value is not extreme "
            f"{'(interior of the tested set)' if best['bc_weight'] not in (s['runs'][0]['bc_weight'], s['runs'][-1]['bc_weight']) else '(at an end of the tested set: extend the range)'} | self-adaptive / annealed weights |"
        )
    # (F4) spectral bias
    sp = [(r["problem"], r["value"], r["spectrum"]) for r in recs if r.get("spectrum")]
    if sp:
        med_share = float(np.median([q[2]["error_high_band_fraction"] for q in sp]))
        worst = max(sp, key=lambda q: q[2]["error_to_reference_ratio_high"])
        sup = (
            f"supported: a median {med_share:.2f} of the error energy sits in the high band"
            if med_share >= 0.1
            else f"NOT supported as the dominant failure: only a median {med_share:.2f} of the error energy is above k_cut (error is mostly low-wavenumber)"
        )
        L.append(
            f"| Spectral bias | error/reference amplitude ratio above k = {sp[0][2]['k_cut']:g}: worst {worst[2]['error_to_reference_ratio_high']:.2f} "
            f"({worst[0]}, {worst[1]:g}; reference high-band energy fraction {worst[2]['reference_high_band_fraction']:.1e}), low-band median "
            f"{np.median([q[2]['error_to_reference_ratio_low'] for q in sp]):.2e} | {sup} | Fourier features, modified MLP |"
        )
    # (F5) solver context
    for name in names:
        sel = [r for r in recs if r["problem"] == name]
        better = sum(1 for q in sel if q["reference_solvers"]["spectral"]["rel_l2"] < q["rel_l2"])
        tp, ts = (
            np.median([q["wall_s"] for q in sel]),
            np.median([q["reference_solvers"]["spectral"]["wall_s"] for q in sel]),
        )
        L.append(
            f"| PINN vs solvers ({name}) | Chebyshev more accurate than the PINN in {better}/{len(sel)} runs; PINN training {tp:.0f} s vs Chebyshev {ts:.2f} s (median) | "
            f"{'for one query the solver is both faster and more accurate here' if better == len(sel) and tp > ts else 'mixed'} | break-even study in Phase 6 (RQ5) |"
        )
    L += [
        "",
        "Caveat: smoke budget (small network, short training). Failures here may shrink or vanish with the full profile; "
        "that is what Phase 4 measures. Chebyshev N is user-set (`evaluation.reference_solvers.spectral_N`) and can itself be under-resolved at large Pe.",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L
