"""Summary of a user-data demo (experiments/run_user_demo.py): every step's result on the user's data file, from the
saved metrics of results/<step>_<tag>/. For a SYNTHETIC example whose true parameters are written in the data file's
header ('# ... true parameters {...}'), each estimate / interval is also checked against that hidden truth.

    python experiments/user_demo_summary.py [--tag cylinder_demo] [--config ...]
"""

from __future__ import annotations

import argparse
import ast
import json
import re

import numpy as np

from aerosynapse.thermal.experiments.p5_3_classical import _restore
from aerosynapse.thermal.inverse import spec as IS
from aerosynapse.thermal.utils.experiment import ROOT

UNK = ("alpha", "k", "h")


def hidden_truth(path: str) -> dict | None:
    """The 'true parameters {...}' of a synthetic example file's header comments, if present."""
    p = ROOT / path
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        m = re.search(r"true parameters (\{.*\})", line)
        if m:
            return ast.literal_eval(m.group(1))
    return None


def _load(step: str, tag: str) -> dict | None:
    f = ROOT / "results" / f"{step}_{tag}" / "metrics.json"
    return _restore(json.loads(f.read_text(encoding="utf-8"))) if f.exists() else None


def _iv(lo: float, hi: float, k: str, truth: dict | None) -> str:
    cover = "" if truth is None else (" ✓" if lo <= truth[k] <= hi else " ✗")
    return f"[{lo:.3g}, {hi:.3g}]{cover}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", default="cylinder_demo")
    ap.add_argument("--config", action="append", default=None)
    a = ap.parse_args()
    cfgs = a.config or ["configs/inverse/user_case.yaml", "configs/inverse/examples/user_cylinder.yaml"]
    spec = IS.load_spec(cfgs)
    truth = hidden_truth(spec["data"]["file"])
    b = spec["body"]
    L = [
        f"# Your data and shape in every Phase 5 step — `{a.tag}` (auto-generated by experiments/user_demo_summary.py)",
        "",
        f"Configuration: {' + '.join(cfgs)}; body {b.get('shape')} (L {b['L']:g} m, q_vol {b['q_vol']:g} W/m³); data file "
        f"{spec['data']['file']} ({IS.data_design(spec)['n_readings']} readings, {len(IS.sensor_positions(spec))} sensors × "
        f"{len(IS.measurement_times(spec))} times, noise level {spec['data']['level']:.3g} from its sigma column); nominal parameters "
        f"{spec['parameters']}.",
        ""
        if truth is None
        else f"Hidden truth (synthetic example, from the file header; NOT used by any step): {truth}. "
        "✓ / ✗ = the interval contains / misses it.",
        "",
    ]
    sm = ROOT / "results" / f"user_demo_{a.tag}" / "summary.json"
    if sm.exists():
        L += ["| step | exit code | run time |", "|---|---|---|"]
        L += [
            f"| {x['step']} | {x['exit_code']} | {x['seconds'] / 60:.1f} min |"
            for x in json.loads(sm.read_text(encoding="utf-8"))
        ]
        L.append("")
    L += ["| step | result on your data | α [m²/s] | k [W/(m K)] | h [W/(m² K)] |", "|---|---|---|---|---|"]
    m1 = _load("p5_1_identifiability", a.tag)
    if m1:
        lv = min(m1["scenarios"]["with_source"]["levels"], key=lambda s: abs(float(s) - float(m1["reference_level"])))
        cr = m1["scenarios"]["with_source"]["levels"][lv]["crlb_percent"]
        L.append(
            "| 5.1 identifiability | Cramér–Rao bound (1σ) of your design at the nominal values, your noise | "
            + " | ".join(f"± {cr[k]:.3g} %" for k in UNK)
            + " |"
        )
        d = m1.get("design") or {}
        if d.get("optimal"):
            L.append(
                f"| 5.1 optimal design | bound with the optimised design ({len(d['optimal_design']['positions'])} sensors, t1 "
                f"{d['optimal_design'].get('t1', float('nan')):.0f} s) | "
                + " | ".join(f"± {d['optimal']['crlb_percent'][k]:.3g} %" for k in UNK)
                + " |"
            )
    m3 = _load("p5_3_classical", a.tag)
    if m3:
        f = m3["cases"]["base"]["fit"]
        L.append(
            "| 5.3 least squares (FDM) | estimate [95 % interval] | "
            + " | ".join(f"{f['estimates'][k]:.4g} {_iv(*f['ci95'][k], k, truth)}" for k in UNK)
            + " |"
        )
        ms = m3["cases"]["base"]["multistart"]
        L.append(
            f"| 5.3 multi-start | {ms['n_at_best']} of {len(ms['chi2_per_reading'])} starts reach the best fit | — | — | — |"
        )
    m2 = _load("p5_2_pinn_inverse", a.tag)
    if m2:
        for r in m2["records"]:
            L.append(
                f"| 5.2 PINN {r['variant']} (seed {r['seed']}) | estimate (data RMSE {r['data_rmse_K']:.3f} K) | "
                + " | ".join(f"{r['estimates'][k]:.4g}" for k in UNK)
                + " |"
            )
    m5 = _load("p5_5_uq", a.tag)
    if m5:
        c = next(iter(m5["cases"].values()))
        iv = c["seed"]["intervals"]["0.95"]
        for meth, lab in (
            ("gauss_newton", "Gauss–Newton"),
            ("bootstrap_parametric", "parametric bootstrap"),
            ("bootstrap_residual", "residual bootstrap"),
            ("posterior", "Bayesian posterior"),
        ):
            if meth in iv:
                L.append(
                    f"| 5.5 {lab} | 95 % interval | "
                    + " | ".join(_iv(np.exp(iv[meth][k][0]), np.exp(iv[meth][k][1]), k, truth) for k in UNK)
                    + " |"
                )
        cal = c.get("calibration")
        if cal:
            cv = cal["coverage"]
            L.append(
                f"| 5.5 calibration | 95 % coverage over {cal['datasets']} synthetic datasets (GN / posterior) | "
                + " | ".join(
                    f"{100 * cv['gauss_newton']['0.95'][k]:.0f} / {100 * cv['posterior']['0.95'][k]:.0f} %" for k in UNK
                )
                + " |"
            )
    m6 = _load("p5_6_confounding", a.tag)
    if m6:
        r = next(x for x in m6["rows"] if x["group"] == "configured")

        def piv(k):
            lo, hi = r["profiles"][k]["ci95_log"]
            lo_v, hi_v = (0.0 if lo is None else float(np.exp(lo))), (np.inf if hi is None else float(np.exp(hi)))
            return _iv(lo_v, hi_v, k, truth)

        L.append(
            "| 5.6 profile likelihood | 95 % interval (not linearised) | " + " | ".join(piv(k) for k in UNK) + " |"
        )
    m4 = _load("p5_4_robustness", a.tag)
    if m4:
        rows = [x for x in m4["rows"] if x.get("mc", {}).get("std_over_crlb")]
        rat = [v for x in rows for v in x["mc"]["std_over_crlb"].values()]
        cov = [100 * v for x in rows for v in x["mc"]["coverage95"].values()]
        L.append(
            f"| 5.4 robustness (synthetic around your setup) | {len(rows)} settings: sample std / CRLB {min(rat):.2f}-{max(rat):.2f}, "
            f"95 % coverage {min(cov):.0f}-{max(cov):.0f} % | — | — | — |"
        )
    L.append("")
    out = ROOT / "results" / f"user_demo_{a.tag}" / "summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
