"""Step 4.1 report: architecture comparison table. All statements are measurements; wording depends on the evidence.

Rules: best architecture per case is named only with its error and whether it meets the target; improvement over the
baseline is a ratio; the truth-free validation loss is called a usable proxy only if Spearman(val_loss, rel_L2) >= 0.7
across all runs; sigma selection by validation loss is compared with the truth-based minimum; few seeds are flagged.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.stats import spearmanr


def _agg(rs: list[dict], key: str) -> tuple[float, float]:
    v = np.array([r[key] for r in rs], float)
    return float(v.mean()), float(v.std()) if len(v) > 1 else 0.0


def user_data_lines(recs: list[dict], label_key: str) -> list[str]:
    """Errors at user-provided data points (aerosynapse.thermal.pinn.userdata); empty when no case has user data."""
    rows = [r for r in recs if r.get("user_data")]
    if not rows:
        return []
    L = [
        "## User data",
        "",
        "Errors of the trained model at the user's data points (pressure compared mean-free). Role train/both: these "
        "points were also TRAINED on, so the error is a fit error, not an independent validation.",
        "",
        "| Case | Variant | Seed | Source | Role | Points (dropped) | rel L2 / L∞ per field |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        case = r.get("case", f"{r.get('problem')} {r.get('value', '')}")
        for src, m in r["user_data"].items():
            fields = [k[len("rel_l2_") :] for k in m if k.startswith("rel_l2_")]
            cells = "; ".join(f"{f}: {m['rel_l2_' + f]:.2e} / {m['linf_' + f]:.2e}" for f in fields)
            L.append(
                f"| {case} | {r[label_key]} | {r['seed']} | {src} | {m['role']} | {m['n']} ({m.get('n_dropped', 0)}) | {cells} |"
            )
    return L + [""]


def arch_table(recs: list[dict], sweep: dict | None, spec: dict, path: Path, tag: str) -> list[str]:
    tgt = spec["evaluation"]["target_rel_l2"]
    seeds = sorted({r["seed"] for r in recs})
    t, net = spec["training"], spec["network"]
    L = [
        f"# Step 4.1 architecture comparison — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_1_architectures_{tag}/metrics.json)",
        "",
        f"Base network {net['depth']}x{net['width']} (width/depth shared by all architectures; parameter counts differ and are listed), "
        f"Adam {t['adam']['epochs']} + L-BFGS {t['lbfgs']['iterations']}, {spec['sampling']['n_pde']} PDE points, target rel L2 < {tgt:g}, "
        f"seeds {seeds}, profile `{spec['profile']}`.",
        "",
    ]
    cases = list(dict.fromkeys((r["problem"], r["value"]) for r in recs))
    labels = list(dict.fromkeys(r["label"] for r in recs))
    for prob, val in cases:
        sel = [r for r in recs if r["problem"] == prob and r["value"] == val]
        L += [
            f"## {prob}, {sel[0]['parameter']} = {val:g}",
            "",
            "| Architecture | rel L2 (mean ± std) | L∞ | rel H¹ | val loss (truth-free) | params | train s | meets target | status |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        rows = []
        for lab in labels:
            rs = [r for r in sel if r["label"] == lab]
            if not rs:
                continue
            m, s = _agg(rs, "rel_l2")
            rows.append((m, lab, rs))
        for m, lab, rs in sorted(rows, key=lambda q: q[0]):
            _, s = _agg(rs, "rel_l2")
            L.append(
                f"| {lab} | {m:.3e} ± {s:.1e} | {_agg(rs, 'linf')[0]:.2e} | {_agg(rs, 'rel_h1')[0]:.2e} | {_agg(rs, 'val_loss')[0]:.2e} | "
                f"{rs[0]['n_params']} | {_agg(rs, 'wall_s')[0]:.0f} | {'yes' if m < tgt else '**no**'} | {','.join(sorted({r['status'] for r in rs}))} |"
            )
        best = min(rows, key=lambda q: q[0])
        base = next((m for m, lab, _ in rows if lab == "mlp"), None)
        meets = [lab for m, lab, _ in rows if m < tgt]
        stmt = f"Best: **{best[1]}** at rel L2 {best[0]:.2e}"
        if base is not None and best[1] != "mlp":
            stmt += f" ({base / best[0]:.1f}x lower than the baseline MLP's {base:.2e})"
        elif best[1] == "mlp":
            stmt += " (the baseline MLP is the best here)"
        stmt += f". Meeting the target: {', '.join(meets) if meets else 'none — no architecture solved this case within this budget'}."
        L += ["", stmt, ""]
    allr = [r for r in recs if np.isfinite(r["val_loss"]) and np.isfinite(r["rel_l2"])]
    if len(allr) >= 4:
        rho = float(spearmanr([r["val_loss"] for r in allr], [r["rel_l2"] for r in allr]).statistic)
        # within-case ordering: do the validation loss and the true error rank two architectures the same way?
        conc, tot, worst = 0, 0, None
        for prob, val in cases:
            sel = [r for r in allr if r["problem"] == prob and r["value"] == val]
            by_label = {
                lab: (
                    np.mean([r["val_loss"] for r in sel if r["label"] == lab]),
                    np.mean([r["rel_l2"] for r in sel if r["label"] == lab]),
                )
                for lab in dict.fromkeys(r["label"] for r in sel)
            }
            labs = list(by_label)
            for i in range(len(labs)):
                for j in range(i + 1, len(labs)):
                    (vi, ei), (vj, ej) = by_label[labs[i]], by_label[labs[j]]
                    tot += 1
                    if (vi - vj) * (ei - ej) > 0:
                        conc += 1
                    else:
                        ratio = max(ei, ej) / max(min(ei, ej), 1e-300)
                        if worst is None or ratio > worst[0]:
                            better = labs[i] if ei < ej else labs[j]
                            other = labs[j] if ei < ej else labs[i]
                            worst = (ratio, prob, val, better, other)
        frac = conc / tot if tot else float("nan")
        if rho >= 0.7 and frac >= 0.8:
            verdict = "the validation loss is a usable truth-free proxy for the error across these runs"
        elif rho >= 0.7:
            verdict = (
                f"pooled across cases the validation loss tracks the error, but WITHIN a case it ranks architectures correctly for only "
                f"{100 * frac:.0f}% of pairs: it is not reliable for choosing between architectures"
            )
        else:
            verdict = "the validation loss is NOT a reliable proxy for the error across these runs (a low loss does not guarantee a low error)"
        extra = ""
        if worst is not None:
            extra = (
                f" Largest misranking: in {worst[1]} {worst[2]:g}, {worst[3]} has a {worst[0]:.1f}x lower error than {worst[4]} "
                "but not a lower validation loss."
            )
        L += [
            "## Truth-free selection quality",
            "",
            f"Spearman(validation loss, rel L2) over {len(allr)} runs = {rho:.2f}; within-case pairwise agreement {conc}/{tot} "
            f"({100 * frac:.0f}%): {verdict}.{extra}",
            "",
        ]
    if sweep:
        tuned = sweep["selected_sigma"] if "selected_sigma" in sweep else None
        sc = (sweep["case"]["problem"], sweep["case"]["value"])
        bad = []
        for prob, val in cases:
            if (prob, val) == sc:
                continue
            f_ = [r["rel_l2"] for r in recs if r["problem"] == prob and r["value"] == val and r["label"] == "fourier"]
            m_ = [r["rel_l2"] for r in recs if r["problem"] == prob and r["value"] == val and r["label"] == "mlp"]
            if f_ and m_ and np.mean(f_) > np.mean(m_):
                bad.append(f"{prob} {val:g} (Fourier {np.mean(f_):.2e} vs MLP {np.mean(m_):.2e})")
        if tuned is not None and bad:
            L += [
                "## Does the tuned σ transfer?",
                "",
                f"σ = {tuned:g} was tuned on {sc[0]} {sc[1]:g} only. On other cases it is worse than the baseline MLP: {'; '.join(bad)}. "
                "A single σ for all input columns (x and t) and all cases is not appropriate; tune per case or per column (`fourier.sigma` accepts one value per input column).",
                "",
            ]
    if sweep:
        L += [
            "## Fourier σ sweep (selected by validation loss)",
            "",
            f"Case {sweep['case']['problem']} {sweep['case']['value']:g}, seed {sweep['seed']}.",
            "",
            "| σ | val loss | rel L2 | status |",
            "|---|---|---|---|",
        ]
        for s in sweep["runs"]:
            L.append(f"| {s['sigma']:g} | {s['val_loss']:.2e} | {s['rel_l2']:.2e} | {s['status']} |")
        by_val = min(sweep["runs"], key=lambda q: q["val_loss"])["sigma"]
        by_truth = min(sweep["runs"], key=lambda q: q["rel_l2"])["sigma"]
        agree = "agree" if by_val == by_truth else f"DISAGREE (truth-based minimum at σ = {by_truth:g})"
        ends = by_val in (sweep["runs"][0]["sigma"], sweep["runs"][-1]["sigma"])
        L += [
            "",
            f"Selected σ = **{by_val:g}** (minimum validation loss); the truth-based choice and the truth-free choice {agree}."
            + (
                " The selected value is at an end of the tested range: extend `arch_study.sigma_sweep.values`."
                if ends
                else ""
            ),
            "",
        ]
    if len(seeds) < 3:
        L += [
            f"Caveat: {len(seeds)} seed(s). Differences smaller than seed-to-seed variation cannot be excluded; the ablation in Step 4.7 uses >= 3 seeds. "
            "Parameter counts differ between architectures, so a ranking mixes architecture and capacity effects.",
            "",
        ]
    L += user_data_lines(recs, "label")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


# --- Step 4.2 --------------------------------------------------------------------------------------------------------
INACTIVE = 1.2  # Step 4.3: final weight spread below this = method effectively inactive
NOT_CAPTURED = 0.3  # Step 4.5: worst-field rel L2 at or above this = solution not captured (comparisons uninformative)
EFFECT = 2.0  # a factor below this is not called an effect (one seed: seed-to-seed variation is unknown)
ROUNDOFF = 1e-10


def _effect(base: float, var: float) -> str:
    f = base / max(var, 1e-300)
    if abs(f - 1.0) < 1e-9:
        return "identical (to round-off)"
    if f >= EFFECT:
        return f"{f:.1f}x lower"
    if f <= 1 / EFFECT:
        return f"{1 / f:.1f}x HIGHER"
    return f"within a factor {EFFECT:g} (no effect claimed)"


def _mean(rs: list[dict], k: str) -> float:
    v = [r[k] for r in rs if r.get(k) is not None and np.isfinite(r[k])]
    return float(np.mean(v)) if v else float("nan")


def _fmt(v: float, f: str = ".2e") -> str:
    return "—" if v is None or not np.isfinite(v) else format(v, f)


def formulation_table(recs: list[dict], refs: dict, spec: dict, path: Path, tag: str) -> list[str]:
    """Step 4.2 report. Statements are produced by rules from the measurements:
    - effects of one changed factor are stated as ratios vs the `primitive` variant, and only beyond a factor 2;
    - 'divergence-free to round-off' / 'constraint holds to round-off' only if the measured maximum is < 1e-10;
    - PINN errors below the cavity reference's coarse-fine difference are called unresolvable;
    - the truth-free validation loss is assessed by within-case pairwise ranking agreement."""
    tgt = spec["evaluation"]["target_rel_l2"]
    seeds = sorted({r["seed"] for r in recs})
    t, net = spec["training"], spec["network"]
    L = [
        f"# Step 4.2 formulation comparison — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_2_formulations_{tag}/metrics.json)",
        "",
        f"Network {net.get('arch', 'mlp')} {net['depth']}x{net['width']} {net['activation']} (3 outputs for the stream function, 4 for primitive), "
        f"Adam {t['adam']['epochs']} + L-BFGS {t['lbfgs']['iterations']}, {spec['sampling']['n_pde']} interior + 4x{spec['sampling']['n_bc']} wall points, "
        f"weights {spec['loss']['weights']}, seeds {seeds}, profile `{spec['profile']}`. "
        "Errors: relative L2 on the truth grid; pressure compared mean-free (gauge-invariant). 'worst' = max over u, v, θ. "
        "Validation loss = unnormalised primitive residuals + ALL wall conditions on independent points (truth-free, comparable across formulations; "
        "training losses are not).",
        "",
    ]
    cases = list(dict.fromkeys(r["case"] for r in recs))
    labels = list(dict.fromkeys(r["variant"] for r in recs))
    for case in cases:
        sel = [r for r in recs if r["case"] == case]
        ref = refs.get(case, {})
        L += [f"## {case}", ""]
        if "coarse_fine_diff" in ref:
            d = ref["coarse_fine_diff"]
            L += [
                f"Truth: {ref['kind']} on {ref['n_fine']}² cells (Newton |R| = {ref['newton']['fine']['newton_residual']:.1e}). "
                f"Reference uncertainty (relative difference {ref['n_coarse']}² vs {ref['n_fine']}²): u {d['u']:.2e}, v {d['v']:.2e}, θ {d['theta']:.2e}, "
                f"p {d['p']:.2e}, Nu_top {d['nu_top']:.2e}. PINN errors below these values cannot be resolved against this reference.",
                "",
            ]
        else:
            L += [f"Truth: {ref.get('kind', 'exact')}.", ""]
        cav = any("nu_top_rel_err" in r for r in sel)
        L += [
            "| Variant | form | hard BC | gauge | normalise | worst rel L2 (u,v,θ) | u | v | θ | p | max |div| | val loss | "
            + ("Nu_top err | " if cav else "")
            + "params | s | status |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|" + ("---|" if cav else "") + "---|---|---|",
        ]
        rows = []
        for lb in labels:
            rs = [r for r in sel if r["variant"] == lb]
            if rs:
                rows.append((_mean(rs, "rel_l2_max"), lb, rs))
        for m, lb, rs in sorted(rows, key=lambda q: q[0]):
            r0 = rs[0]
            sd = f" ± {np.std([r['rel_l2_max'] for r in rs]):.1e}" if len(rs) > 1 else ""
            L.append(
                f"| {lb} | {r0['kind']} | {'yes' if r0['hard_bc'] else 'no'} | {r0['gauge']} | {r0['normalise']} | {m:.3e}{sd} | "
                f"{_mean(rs, 'rel_l2_u'):.2e} | {_mean(rs, 'rel_l2_v'):.2e} | {_mean(rs, 'rel_l2_theta'):.2e} | {_mean(rs, 'rel_l2_p'):.2e} | "
                f"{_mean(rs, 'max_div'):.1e} | {_mean(rs, 'val_loss'):.2e} | "
                + (f"{_fmt(_mean(rs, 'nu_top_rel_err'))} | " if cav else "")
                + f"{r0['n_params']} | {_mean(rs, 'wall_s'):.0f} | {','.join(sorted({r['status'] for r in rs}))} |"
            )
        best = min(rows, key=lambda q: q[0])
        meets = [lb for m, lb, _ in rows if m < tgt]
        L += [
            "",
            f"Best (worst-field error): **{best[1]}** at {best[0]:.2e}. Below the target {tgt:g}: "
            + (", ".join(meets) if meets else "none — no formulation solved this case within this budget")
            + ".",
        ]
        bp = min(rows, key=lambda q: _mean(q[2], "rel_l2_p"))
        L.append(f"Lowest pressure error: **{bp[1]}** at {_mean(bp[2], 'rel_l2_p'):.2e}.")
        if "coarse_fine_diff" in ref:
            d = ref["coarse_fine_diff"]
            below = [
                f"{k} ({_mean(best[2], 'rel_l2_' + k):.2e} < {d[k]:.2e})"
                for k in ("u", "v", "theta", "p")
                if _mean(best[2], "rel_l2_" + k) < d[k]
            ]
            L.append(
                "Best-variant fields below the reference uncertainty (not resolvable): " + ", ".join(below) + "."
                if below
                else "All best-variant field errors exceed the reference uncertainty, so they are PINN errors, not reference errors."
            )
        base = next((rs for m, lb, rs in rows if lb == "primitive"), None)
        if base is not None:
            L += [
                "",
                "Effect relative to `primitive` (ratio of mean errors; one factor changed unless the name combines several):",
                "",
            ]
            L += ["| Variant | worst-field error | pressure error | val loss | train time |", "|---|---|---|---|---|"]
            for m, lb, rs in rows:
                if lb == "primitive":
                    continue
                L.append(
                    f"| {lb} | {_effect(_mean(base, 'rel_l2_max'), m)} | {_effect(_mean(base, 'rel_l2_p'), _mean(rs, 'rel_l2_p'))} | "
                    f"{_effect(_mean(base, 'val_loss'), _mean(rs, 'val_loss'))} | {_mean(rs, 'wall_s') / max(_mean(base, 'wall_s'), 1e-9):.1f}x |"
                )
            keys = ("rel_l2_u", "rel_l2_v", "rel_l2_theta", "rel_l2_p", "max_div", "val_loss")
            same = [
                lb
                for m, lb, rs in rows
                if lb != "primitive"
                and all(abs(_mean(rs, k) - _mean(base, k)) <= 1e-9 * max(abs(_mean(base, k)), 1e-300) for k in keys)
            ]
            if same:
                L += [
                    "",
                    f"Identical to `primitive` in every error, divergence and validation metric (to round-off): {', '.join(same)}.",
                ]
        L.append("")
        psi = [r for r in sel if r["kind"] == "streamfunction"]
        prim = [r for r in sel if r["kind"] == "primitive"]
        if psi:
            md = max(r["max_div"] for r in psi)
            L.append(
                f"Stream function: max |div u| = {md:.1e} over its runs: "
                + (
                    "divergence-free to round-off, as constructed."
                    if md < ROUNDOFF
                    else "NOT at round-off level — check the derivative code."
                )
                + (
                    f" Primitive runs: max |div u| {min(r['max_div'] for r in prim):.1e} … {max(r['max_div'] for r in prim):.1e} (continuity is only a loss term)."
                    if prim
                    else ""
                )
            )
        hard_p = [r for r in sel if r["hard_bc"] and r["kind"] == "primitive"]
        hard_s = [r for r in sel if r["hard_bc"] and r["kind"] == "streamfunction"]
        hard_t = [r for r in sel if r["hard_bc"] and np.isfinite(r.get("bc_max_theta_dirichlet", float("nan")))]
        chk: list[tuple[str, float]] = []
        if hard_p:
            chk.append(
                (
                    "primitive velocity on all walls",
                    max(max(r["bc_max_normal"], r["bc_max_tangential"]) for r in hard_p),
                )
            )
        if hard_s:
            chk.append(("stream-function normal velocity", max(r["bc_max_normal"] for r in hard_s)))
        if hard_t:
            chk.append(("θ on Dirichlet walls", max(r["bc_max_theta_dirichlet"] for r in hard_t)))
        if chk:
            ok = all(v < ROUNDOFF for _, v in chk)
            L.append(
                "Hard constraints, measured max wall error: "
                + "; ".join(f"{n} {v:.1e}" for n, v in chk)
                + (" — exact to round-off." if ok else " — NOT at round-off: investigate.")
            )
        soft = [r for r in sel if not r["hard_bc"]]
        if soft:
            L.append(
                f"Soft-constraint runs: max wall error velocity {max(max(r['bc_max_normal'], r['bc_max_tangential']) for r in soft):.1e}, "
                f"θ (Dirichlet walls) {_fmt(max(r.get('bc_max_theta_dirichlet', float('nan')) for r in soft), '.1e')}."
            )
        L.append("")
    # truth-free selection quality (within case)
    conc = tot = 0
    worst = None
    for case in cases:
        by = {
            lb: (
                _mean([r for r in recs if r["case"] == case and r["variant"] == lb], "val_loss"),
                _mean([r for r in recs if r["case"] == case and r["variant"] == lb], "rel_l2_max"),
            )
            for lb in labels
            if any(r["case"] == case and r["variant"] == lb for r in recs)
        }
        ks = list(by)
        for i in range(len(ks)):
            for j in range(i + 1, len(ks)):
                (vi, ei), (vj, ej) = by[ks[i]], by[ks[j]]
                if not all(np.isfinite([vi, ei, vj, ej])):
                    continue
                tot += 1
                if (vi - vj) * (ei - ej) > 0:
                    conc += 1
                else:
                    ratio = max(ei, ej) / max(min(ei, ej), 1e-300)
                    if worst is None or ratio > worst[0]:
                        worst = (ratio, case, ks[i] if ei < ej else ks[j], ks[j] if ei < ej else ks[i])
    if tot:
        frac = conc / tot
        verdict = (
            "it ranks formulations consistently with the true error"
            if frac >= 0.8
            else "it is NOT reliable for choosing between formulations"
        )
        L += [
            "## Truth-free selection quality",
            "",
            f"Within-case pairwise agreement between the validation loss and the worst-field error: {conc}/{tot} ({100 * frac:.0f}%): {verdict}."
            + (
                f" Largest misranking: in {worst[1]}, {worst[2]} has a {worst[0]:.1f}x lower error than {worst[3]} but not a lower validation loss."
                if worst
                else ""
            ),
            "",
        ]
    if len(cases) > 1:
        bests = {
            c: min(
                labels,
                key=lambda lb, c=c: (
                    _mean([r for r in recs if r["case"] == c and r["variant"] == lb], "rel_l2_max")
                    if any(r["case"] == c and r["variant"] == lb for r in recs)
                    else np.inf
                ),
            )
            for c in cases
        }
        same = len(set(bests.values())) == 1

        def near(c: str) -> set[str]:  # variants within the effect factor of the case's best
            m = {lb: _mean([r for r in recs if r["case"] == c and r["variant"] == lb], "rel_l2_max") for lb in labels}
            b = min(v for v in m.values() if np.isfinite(v))
            return {lb for lb, v in m.items() if np.isfinite(v) and v <= EFFECT * b}

        common = [lb for lb in labels if all(lb in near(c) for c in cases)]
        L += [
            "## Consistency across cases",
            "",
            (
                "The same variant is best in every case: "
                if same
                else "The nominally best variant differs between cases: "
            )
            + ", ".join(f"{c} → {b}" for c, b in bests.items())
            + ". "
            + (
                f"Within a factor {EFFECT:g} of the best worst-field error in EVERY case: {', '.join(common)}."
                if common
                else f"No variant is within a factor {EFFECT:g} of the best in every case: no single formulation recommendation follows."
            ),
            "",
        ]
    if len(seeds) < 3:
        L += [
            f"Caveat: {len(seeds)} seed(s); differences within a factor {EFFECT:g} are not called effects. Seed statistics and the ablation are Step 4.7. "
            "Training losses differ in their terms between formulations and are not compared.",
            "",
        ]
    L += user_data_lines(recs, "variant")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


# --- Step 4.3 --------------------------------------------------------------------------------------------------------
def _case_mean(recs: list[dict], case: str, method: str, key: str) -> float:
    return _mean([r for r in recs if r["case"] == case and r["method"] == method], key)


def balance_table(recs: list[dict], refs: dict, spec: dict, path: Path, tag: str) -> list[str]:
    """Step 4.3 report. Rules: effects vs `fixed` are ratios and only named beyond a factor 2; a method 'reduced the
    gradient imbalance' if its weighted gradient-norm spread is below that of fixed weights; the truth-free validation
    metric is assessed by within-case pairwise agreement; clamped weights and failed runs are listed explicitly."""
    tgt = spec["evaluation"]["target_rel_l2"]
    seeds = sorted({r["seed"] for r in recs})
    t, net = spec["training"], spec["network"]
    cases = list(dict.fromkeys(r["case"] for r in recs))
    methods = list(dict.fromkeys(r["method"] for r in recs))
    L = [
        f"# Step 4.3 loss-balancing comparison — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_3_balancing_{tag}/metrics.json)",
        "",
        f"Network {net.get('arch', 'mlp')} {net['depth']}x{net['width']} {net['activation']}, Adam {t['adam']['epochs']} + L-BFGS "
        f"{t['lbfgs']['iterations']}, {spec['sampling']['n_pde']} PDE points, seeds {seeds}, profile `{spec['profile']}`. "
        "Error: rel L2 vs truth (2D: worst of u, v, θ). Adaptive weights are updated during Adam and frozen for L-BFGS; "
        "`loss.weights` (all 1 here) multiply them. Validation loss: 1D = fixed-weight loss on independent points; "
        "2D = formulation-independent validation loss (Step 4.2) — the same yardstick for every method (training losses "
        "are not comparable across methods). Weight spread = max/min final effective weight; gradient spread = max/min "
        "over components of ||∇θ L_k|| (unweighted → weighted with the final weights), at the last Adam batch.",
        "",
    ]
    fixed_err = {c: _case_mean(recs, c, "fixed", "err") for c in cases}
    fixed_g = {c: _case_mean(recs, c, "fixed", "grad_spread_weighted") for c in cases}
    fixed_t = {c: _case_mean(recs, c, "fixed", "wall_s") for c in cases}
    med_t = {c: float(np.median([r["wall_s"] for r in recs if r["case"] == c])) for c in cases}
    t_ok = {c: np.isfinite(fixed_t[c]) and 1 / EFFECT <= fixed_t[c] / med_t[c] <= EFFECT for c in cases}
    for c in cases:
        sel = [r for r in recs if r["case"] == c]
        two_d = sel[0]["dim"] == 2
        L += [f"## {c}" + (f" ({sel[0].get('formulation', '')})" if two_d else ""), ""]
        ref = refs.get(sel[0]["problem"])
        if ref:
            d = ref["coarse_fine_diff"]
            L += [
                f"Reference uncertainty (coarse-fine): u {d['u']:.2e}, v {d['v']:.2e}, θ {d['theta']:.2e}, p {d['p']:.2e}.",
                "",
            ]
        L += [
            "| Method | error | "
            + ("p error | " if two_d else "")
            + "val loss | weight spread | grad spread (unw → w) | clamped | s | cost vs fixed | status |",
            "|---|---|" + ("---|" if two_d else "") + "---|---|---|---|---|---|---|",
        ]
        rows = [(_case_mean(recs, c, m, "err"), m, [r for r in sel if r["method"] == m]) for m in methods]
        rows = [q for q in rows if q[2]]
        for m_, lb, rs in sorted(rows, key=lambda q: (not np.isfinite(q[0]), q[0])):
            sd = f" ± {np.std([r['err'] for r in rs]):.1e}" if len(rs) > 1 else ""
            cost = _mean(rs, "wall_s") / fixed_t[c] if t_ok[c] and fixed_t[c] > 0 else float("nan")
            L.append(
                f"| {lb} | {m_:.3e}{sd} | "
                + (f"{_mean(rs, 'rel_l2_p'):.2e} | " if two_d else "")
                + f"{_mean(rs, 'val_loss'):.2e} | {_fmt(_mean(rs, 'weight_spread'), '.1e')} | "
                f"{_fmt(_mean(rs, 'grad_spread_unweighted'), '.1e')} → {_fmt(_mean(rs, 'grad_spread_weighted'), '.1e')} | "
                f"{int(sum(r['n_clamped'] for r in rs))} | {_mean(rs, 'wall_s'):.0f} | {_fmt(cost, '.1f')}x | "
                f"{','.join(sorted({r['status'] for r in rs}))} |"
            )
        ok = [q for q in rows if np.isfinite(q[0])]
        L.append("")
        if ok:
            best = min(ok, key=lambda q: q[0])
            meets = [lb for m_, lb, _ in ok if m_ < tgt]
            L.append(
                f"Best: **{best[1]}** at {best[0]:.2e}. Below the target {tgt:g}: "
                + (", ".join(meets) if meets else "none — no method solved this case within this budget")
                + "."
            )
        if np.isfinite(fixed_err[c]):
            fe = fixed_err[c]
            better = [f"{lb} ({fe / m_:.1f}x)" for m_, lb, _ in ok if lb != "fixed" and fe / m_ >= EFFECT]
            worse = [f"{lb} ({m_ / fe:.1f}x)" for m_, lb, _ in ok if lb != "fixed" and m_ / fe >= EFFECT]
            same = [lb for m_, lb, _ in ok if lb != "fixed" and 1 / EFFECT < fe / m_ < EFFECT]
            L.append(
                f"vs fixed ({fe:.2e}): ≥{EFFECT:g}x lower: {', '.join(better) or 'none'}; ≥{EFFECT:g}x HIGHER: "
                f"{', '.join(worse) or 'none'}; within {EFFECT:g}x (no effect claimed): {', '.join(same) or 'none'}."
            )
        bad = [lb for m_, lb, rs in rows if not np.isfinite(m_) or any(r["status"] != "ok" for r in rs)]
        if bad:
            L.append(f"Runs that did not finish normally: {', '.join(bad)}.")
        cl = [
            f"{lb} ({int(sum(r['n_clamped'] for r in rs))})"
            for _, lb, rs in rows
            if sum(r["n_clamped"] for r in rs) > 0
        ]
        if cl:
            L.append(
                f"Weights hit `weight_bounds` (number of clamps): {', '.join(cl)} — those weights are bounded, "
                "not the raw value of the method."
            )
        flat = [lb for _, lb, rs in rows if lb != "fixed" and _mean(rs, "weight_spread") < INACTIVE]
        if flat:
            L.append(
                f"Final weights within a factor {INACTIVE:g} of uniform: {', '.join(flat)} — effectively unweighted at "
                "these settings, so their result says nothing about the method at other hyperparameters."
            )
        slow = [
            f"{r['method']} ({r['wall_s']:.0f} s)" for r in sel if not 1 / EFFECT <= r["wall_s"] / med_t[c] <= EFFECT
        ]
        if slow:
            L.append(
                f"Wall-time outliers (more than {EFFECT:g}x from the case median {med_t[c]:.0f} s): {', '.join(slow)}. "
                + ("The fixed run is one of them, so cost ratios are not given for this case. " if not t_ok[c] else "")
                + "Timings depend on the machine load during the run and are not a property of the method."
            )
        L.append("")
    L += [
        "## Across cases: error ratio fixed / method (> 1 = better than fixed)",
        "",
        "| Method | " + " | ".join(cases) + f" | ≥{EFFECT:g}x better | ≥{EFFECT:g}x worse |",
        "|---|" + "---|" * (len(cases) + 2),
    ]
    for m in methods:
        if m == "fixed":
            continue
        cells, nb, nw = [], 0, 0
        for c in cases:
            e = _case_mean(recs, c, m, "err")
            f = fixed_err[c] / e if np.isfinite(e) and np.isfinite(fixed_err[c]) and e > 0 else float("nan")
            cells.append(_fmt(f, ".2f"))
            nb += bool(np.isfinite(f) and f >= EFFECT)
            nw += bool(np.isfinite(f) and f <= 1 / EFFECT)
        L.append(f"| {m} | " + " | ".join(cells) + f" | {nb} | {nw} |")
    near = []
    for m in methods:
        good = True
        for c in cases:
            vals = [v for v in (_case_mean(recs, c, mm, "err") for mm in methods) if np.isfinite(v)]
            e = _case_mean(recs, c, m, "err")
            good &= bool(vals and np.isfinite(e) and e <= EFFECT * min(vals))
        if good:
            near.append(m)
    L += [
        "",
        f"Within a factor {EFFECT:g} of the best error in EVERY case: "
        + (", ".join(near) if near else "none — no method is uniformly competitive")
        + ".",
        "",
    ]
    pairs = both = 0
    adapt = [r for r in recs if r["method"] != "fixed"]
    for r in adapt:
        fg = fixed_g.get(r["case"], float("nan"))
        if np.isfinite(fg) and np.isfinite(r["grad_spread_weighted"]) and r["grad_spread_weighted"] < fg:
            pairs += 1
            both += bool(fixed_err[r["case"]] / max(r["err"], 1e-300) >= EFFECT)
    verdict = ""
    if pairs:
        verdict = (
            "Reducing the gradient imbalance did NOT reliably reduce the error in these runs."
            if both / pairs < 0.5
            else "Reducing the gradient imbalance went together with a lower error in most of these runs."
        )
    L += [
        "## Gradient balance and error",
        "",
        f"Runs whose weighted gradient-norm spread at the end of Adam is below that of fixed weights: {pairs}/{len(adapt)}; "
        f"of these, {both} also have a ≥{EFFECT:g}x lower error than fixed. {verdict}",
        "",
    ]
    conc = tot = 0
    for c in cases:
        by = {m: (_case_mean(recs, c, m, "val_loss"), _case_mean(recs, c, m, "err")) for m in methods}
        ks = [m for m in by if all(np.isfinite(by[m]))]
        for i in range(len(ks)):
            for j in range(i + 1, len(ks)):
                (vi, ei), (vj, ej) = by[ks[i]], by[ks[j]]
                tot += 1
                conc += (vi - vj) * (ei - ej) > 0
    if tot:
        L += [
            "## Truth-free selection quality",
            "",
            f"Within-case pairwise agreement between the validation metric and the error: {conc}/{tot} "
            f"({100 * conc / tot:.0f}%): "
            + (
                "usable for choosing a balancing method."
                if conc / tot >= 0.8
                else "NOT reliable for choosing a balancing method."
            ),
            "",
        ]
    L += [
        "Notes: the effective weight of self_adaptive is the mean of its pointwise weights. "
        + (
            f"Caveat: {len(seeds)} seed(s); differences within a factor {EFFECT:g} are not called effects "
            "(seed statistics: Step 4.7)."
            if len(seeds) < 3
            else ""
        ),
        "",
    ]
    L += user_data_lines(recs, "method")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


# --- Step 4.4 --------------------------------------------------------------------------------------------------------
def _strat_mean(recs: list[dict], case: str, strat: str, key: str) -> float:
    return _mean([r for r in recs if r["case"] == case and r["strategy"] == strat], key)


def strategy_table(
    recs: list[dict], skipped: list[dict], refs: dict, spec: dict, path: Path, tag: str, baseline: str = "sobol"
) -> list[str]:
    """Step 4.4 report. Rules: effects vs the baseline strategy are ratios named only beyond a factor 2; strategies
    that do not apply to a case are listed as n/a (not run); wall-time outliers suppress cost ratios; the validation
    metric is assessed by within-case pairwise agreement; RAR-D runs whose final point count stayed below the
    baseline's are flagged (unequal budgets)."""
    tgt = spec["evaluation"]["target_rel_l2"]
    seeds = sorted({r["seed"] for r in recs})
    t, net = spec["training"], spec["network"]
    cases = list(dict.fromkeys(r["case"] for r in recs))
    strats = list(dict.fromkeys(r["strategy"] for r in recs))
    L = [
        f"# Step 4.4 sampling and training strategies — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_4_strategies_{tag}/metrics.json)",
        "",
        f"Network {net.get('arch', 'mlp')} {net['depth']}x{net['width']} {net['activation']}; base budget Adam {t['adam']['epochs']} + "
        f"L-BFGS {t['lbfgs']['iterations']}, {spec['sampling']['n_pde']} PDE points (time-marching and curriculum split the SAME "
        f"budget over windows / stages); seeds {seeds}; profile `{spec['profile']}`; each run in its own process. "
        f"Error: rel L2 vs truth (2D: worst of u, v, θ). Baseline for ratios: `{baseline}`. Validation loss: 1D = fixed-weight "
        "physics loss on independent random points; 2D = formulation-independent validation loss.",
        "",
    ]
    base_err = {c: _strat_mean(recs, c, baseline, "err") for c in cases}
    base_t = {c: _strat_mean(recs, c, baseline, "wall_s") for c in cases}
    med_t = {c: float(np.median([r["wall_s"] for r in recs if r["case"] == c])) for c in cases}
    t_ok = {c: np.isfinite(base_t[c]) and 1 / EFFECT <= base_t[c] / med_t[c] <= EFFECT for c in cases}
    for c in cases:
        sel = [r for r in recs if r["case"] == c]
        two_d = sel[0]["dim"] == 2
        L += [f"## {c}" + (f" ({sel[0].get('formulation', '')})" if two_d else ""), ""]
        ref = refs.get(sel[0]["problem"])
        if ref:
            d = ref["coarse_fine_diff"]
            L += [
                f"Reference uncertainty (coarse-fine): u {d['u']:.2e}, v {d['v']:.2e}, θ {d['theta']:.2e}, p {d['p']:.2e}.",
                "",
            ]
        L += [
            "| Strategy | error | "
            + ("p error | " if two_d else "")
            + "val loss | details | s | cost vs baseline | status |",
            "|---|---|" + ("---|" if two_d else "") + "---|---|---|---|---|",
        ]
        rows = [(_strat_mean(recs, c, s, "err"), s, [r for r in sel if r["strategy"] == s]) for s in strats]
        rows = [q for q in rows if q[2]]
        for m_, s, rs in sorted(rows, key=lambda q: (not np.isfinite(q[0]), q[0])):
            r0 = rs[0]
            det = []
            if "n_pde_final" in r0:
                det.append(
                    f"points {r0['n_pde_final']} (k={r0['k']:g}, c={r0['c']:g}, {r0['sampler_updates']} updates)"
                )
            if "causal_eps_final" in r0:
                det.append(f"final ε {r0['causal_eps_final']:g}, min w {r0['causal_min_w']:.2f}")
            if "windows" in r0:
                det.append(f"{r0['windows']} windows")
            if "stages" in r0:
                det.append(f"{r0['parameter']} " + " → ".join(f"{v:g}" for v in r0["stages"]))
            sd = f" ± {np.std([r['err'] for r in rs]):.1e}" if len(rs) > 1 else ""
            cost = _mean(rs, "wall_s") / base_t[c] if t_ok[c] and base_t[c] > 0 else float("nan")
            L.append(
                f"| {s} | {m_:.3e}{sd} | "
                + (f"{_mean(rs, 'rel_l2_p'):.2e} | " if two_d else "")
                + f"{_mean(rs, 'val_loss'):.2e} | {'; '.join(det) or '—'} | {_mean(rs, 'wall_s'):.0f} | {_fmt(cost, '.1f')}x | "
                f"{','.join(sorted({r['status'] for r in rs}))} |"
            )
        ok = [q for q in rows if np.isfinite(q[0])]
        L.append("")
        if ok:
            best = min(ok, key=lambda q: q[0])
            meets = [s for m_, s, _ in ok if m_ < tgt]
            L.append(
                f"Best: **{best[1]}** at {best[0]:.2e}. Below the target {tgt:g}: "
                + (", ".join(meets) if meets else "none — no strategy solved this case within this budget")
                + "."
            )
        if np.isfinite(base_err[c]):
            be = base_err[c]
            better = [f"{s} ({be / m_:.1f}x)" for m_, s, _ in ok if s != baseline and be / m_ >= EFFECT]
            worse = [f"{s} ({m_ / be:.1f}x)" for m_, s, _ in ok if s != baseline and m_ / be >= EFFECT]
            same = [s for m_, s, _ in ok if s != baseline and 1 / EFFECT < be / m_ < EFFECT]
            L.append(
                f"vs {baseline} ({be:.2e}): ≥{EFFECT:g}x lower: {', '.join(better) or 'none'}; ≥{EFFECT:g}x HIGHER: "
                f"{', '.join(worse) or 'none'}; within {EFFECT:g}x (no effect claimed): {', '.join(same) or 'none'}."
            )
        na = [sk for sk in skipped if sk["case"] == c]
        if na:
            L.append("Not applicable (not run): " + "; ".join(f"{sk['strategy']} ({sk['reason']})" for sk in na) + ".")
        short = [
            f"{r['strategy']} ({r['n_pde_final']} < {spec['sampling']['n_pde']})"
            for r in sel
            if "n_pde_final" in r and r["n_pde_final"] < spec["sampling"]["n_pde"]
        ]
        if short:
            L.append(
                f"Final PDE point count below the baseline's (fewer points, not a like-for-like comparison): {', '.join(short)}."
            )
        slow = [
            f"{r['strategy']} ({r['wall_s']:.0f} s)" for r in sel if not 1 / EFFECT <= r["wall_s"] / med_t[c] <= EFFECT
        ]
        if slow:
            L.append(
                f"Wall-time outliers (more than {EFFECT:g}x from the case median {med_t[c]:.0f} s): {', '.join(slow)}. "
                + (
                    "The baseline run is one of them, so cost ratios are not given for this case. "
                    if not t_ok[c]
                    else ""
                )
                + "Timings depend on the machine load and on the strategy's extra work."
            )
        L.append("")
    L += [
        f"## Across cases: error ratio {baseline} / strategy (> 1 = better than {baseline}; n/a = not applicable)",
        "",
        "| Strategy | " + " | ".join(cases) + f" | ≥{EFFECT:g}x better | ≥{EFFECT:g}x worse |",
        "|---|" + "---|" * (len(cases) + 2),
    ]
    for s in strats:
        if s == baseline:
            continue
        cells, nb, nw = [], 0, 0
        for c in cases:
            e = _strat_mean(recs, c, s, "err")
            if not any(r["case"] == c and r["strategy"] == s for r in recs):
                cells.append("n/a")
                continue
            f = base_err[c] / e if np.isfinite(e) and np.isfinite(base_err[c]) and e > 0 else float("nan")
            cells.append(_fmt(f, ".2f"))
            nb += bool(np.isfinite(f) and f >= EFFECT)
            nw += bool(np.isfinite(f) and f <= 1 / EFFECT)
        L.append(f"| {s} | " + " | ".join(cells) + f" | {nb} | {nw} |")
    near = []
    for s in strats:
        good, n_app = True, 0
        for c in cases:
            vals = [v for v in (_strat_mean(recs, c, ss, "err") for ss in strats) if np.isfinite(v)]
            e = _strat_mean(recs, c, s, "err")
            if not any(r["case"] == c and r["strategy"] == s for r in recs):
                continue
            n_app += 1
            good &= bool(vals and np.isfinite(e) and e <= EFFECT * min(vals))
        if good and n_app:
            near.append(f"{s} ({n_app} case{'s' if n_app > 1 else ''})")
    L += [
        "",
        f"Within a factor {EFFECT:g} of the best error in EVERY case where it applies: "
        + (", ".join(near) if near else "none")
        + ".",
        "",
    ]
    conc = tot = 0
    for c in cases:
        by = {s: (_strat_mean(recs, c, s, "val_loss"), _strat_mean(recs, c, s, "err")) for s in strats}
        ks = [s for s in by if all(np.isfinite(by[s]))]
        for i in range(len(ks)):
            for j in range(i + 1, len(ks)):
                (vi, ei), (vj, ej) = by[ks[i]], by[ks[j]]
                tot += 1
                conc += (vi - vj) * (ei - ej) > 0
    if tot:
        L += [
            "## Truth-free selection quality",
            "",
            f"Within-case pairwise agreement between the validation metric and the error: {conc}/{tot} "
            f"({100 * conc / tot:.0f}%): "
            + ("usable for choosing a strategy." if conc / tot >= 0.8 else "NOT reliable for choosing a strategy."),
            "",
        ]
    L += user_data_lines(recs, "strategy")
    if len(seeds) < 3:
        L += [
            f"Caveat: {len(seeds)} seed(s); differences within a factor {EFFECT:g} are not called effects (seed statistics: Step 4.7).",
            "",
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


# --- Step 4.5 --------------------------------------------------------------------------------------------------------
def _pmean(recs: list[dict], variant: str, point: int, key: str) -> float:
    return _mean([r for r in recs if r["variant"] == variant and r["point"] == point], key)


def param_table(
    records: list[dict], runs: list[dict], design: dict, refs: list[dict], spec: dict, path: Path, tag: str
) -> list[str]:
    """Step 4.5 report. Rules: errors per test point vs the steady FV reference; a PINN error below the reference's own
    coarse-fine difference is called unresolvable; parametric vs per-point and extrapolation vs interpolation are
    ratios named only beyond a factor 2; costs are total training times as measured (machine load included)."""
    tgt = spec["evaluation"]["target_rel_l2"]
    ps = spec["param_study"]
    seeds = sorted({r["seed"] for r in records})
    variants = list(dict.fromkeys(r["variant"] for r in records))
    kind = {r["variant"]: r["kind"] for r in records}
    pts = design["points"]
    t, net = spec["training"], spec["network"]
    common = ps.get("common") or {}
    L = [
        f"# Step 4.5a parametric 2D training (Case C) — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_5_parametric_{tag}/metrics.json)",
        "",
        f"Parameter design: {design['source']}. Swept: "
        + ", ".join(f"{n} [{lo:g}, {hi:g}] ({sc})" for n, lo, hi, sc in design["dims"])
        + f"; fixed: {design['fixed']}. Collocation parameters are drawn from the TRAINING box "
        + ", ".join(f"{k} [{a:.4g}, {b:.4g}]" for k, (a, b) in design["train_box"].items())
        + "; extrapolation points lie outside it. Leakage checks: "
        + (
            "all pass"
            if all(v for k, v in design["leakage"].items() if isinstance(v, bool))
            else f"{design['leakage']}"
        )
        + ".",
        "",
        f"Network {net.get('arch', 'mlp')} {net['depth']}x{net['width']} {net['activation']}, formulation {ps['formulation']}, Adam "
        f"{t['adam']['epochs']} + L-BFGS {t['lbfgs']['iterations']} per network, common overrides {common or 'none'}, seeds {seeds}, "
        f"profile `{spec['profile']}`; each run in its own process. Error: worst of u, v, θ (rel L2) on the reference grid; "
        "p mean-free; Nu_top = mean top-wall θ_y.",
        "",
        "## Test points and references",
        "",
        "| point | split | Re | Pr | Bi | Pe | reference | coarse-fine u / v / θ / p | Nu_top ref |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p, r in zip(pts, refs, strict=True):
        v = p["values"]
        d = r["coarse_fine_diff"]
        L.append(
            f"| {p['index']} | {p['split']} | {v.get('Re', float('nan')):.4g} | {v.get('Pr', float('nan')):.4g} | {v.get('Bi', float('nan')):.4g} | "
            f"{v.get('Re', 0) * v.get('Pr', 0):.4g} | {r['kind']}, {r['n_coarse']}²/{r['n_fine']}² | "
            f"{d['u']:.1e} / {d['v']:.1e} / {d['theta']:.1e} / {d['p']:.1e} | {r['nu_top']:.4f} |"
        )
    for key, title in (
        ("rel_l2_max", "Worst-field rel L2 per test point"),
        ("nu_top_rel_err", "Nu_top relative error per test point"),
        ("rel_l2_p", "Pressure rel L2 (mean-free) per test point"),
    ):
        L += [
            "",
            f"## {title}",
            "",
            "| point | split | Pe | " + " | ".join(variants) + " |",
            "|---|---|---|" + "---|" * len(variants),
        ]
        for p in pts:
            v = p["values"]
            cells = [_fmt(_pmean(records, vn, p["index"], key)) for vn in variants]
            L.append(
                f"| {p['index']} | {p['split']} | {v.get('Re', 0) * v.get('Pr', 0):.4g} | " + " | ".join(cells) + " |"
            )
    L += [
        "",
        "## Summary per variant",
        "",
        "| variant | kind | mean / max interp | mean / max extrap | extrap ÷ interp | points < target | unresolvable points | training s (total) | params |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    stats: dict[str, dict] = {}
    for vn in variants:
        rs = [r for r in records if r["variant"] == vn]
        ei = [r["rel_l2_max"] for r in rs if r["split"] == "interp"]
        ee = [r["rel_l2_max"] for r in rs if r["split"] == "extrap"]
        mi, me = (float(np.mean(ei)) if ei else float("nan")), (float(np.mean(ee)) if ee else float("nan"))
        n_ok = sum(r["rel_l2_max"] < tgt for r in rs)
        unres = sorted({r["point"] for r in rs if r["rel_l2_max"] < r["ref_unc_max"]})
        wall = sum(x["wall_s"] for x in runs if x["variant"] == vn)
        npar = rs[0].get("n_params", 0)
        stats[vn] = {"mi": mi, "me": me, "wall": wall}
        L.append(
            f"| {vn} | {kind[vn]} | {_fmt(mi)} / {_fmt(max(ei) if ei else float('nan'))} | {_fmt(me)} / {_fmt(max(ee) if ee else float('nan'))} | "
            f"{_fmt(me / mi if ei and ee else float('nan'), '.2f')} | {n_ok}/{len(rs)} | {unres or 'none'} | {wall:.0f} | {npar} |"
        )
    L.append("")
    meets = [vn for vn in variants if any(r["rel_l2_max"] < tgt for r in records if r["variant"] == vn)]
    L.append(
        f"Target rel L2 < {tgt:g} met by: "
        + (", ".join(meets) if meets else "none — no variant reaches the target at any test point within this budget")
        + "."
    )
