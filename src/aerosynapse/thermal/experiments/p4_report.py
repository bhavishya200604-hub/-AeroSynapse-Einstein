    frac_fail = float(np.mean([e >= NOT_CAPTURED for e in errs])) if errs else 0.0
    if frac_fail >= 0.75:
        L.append(
            f"{100 * frac_fail:.0f}% of all test-point errors are ≥ {NOT_CAPTURED:g} (solution not captured): the ratios below "
            "compare models that FAIL, so they do not show which variant is better or how well extrapolation works."
        )
