def hybrid_table(records: list[dict], refs: list[dict], spec: dict, path: Path, tag: str) -> list[str]:
    """Step 4.6 report (hybrid data + physics vs data-free vs data-only), per case. Statements by rule:
    - 'how little data suffices': the smallest data budget n at which hybrid (a) meets the target rel L2, (b) is at
      least EFFECT x better than data_free, (c) is at least EFFECT x better than data_only at the same n;
    - per-point errors are on held-out cells (not used as data); parametric errors at the test parameter values;
    - when ≥ 75% of a mode's errors are ≥ NOT_CAPTURED the mode is called 'not captured'."""
    tgt = spec["evaluation"]["target_rel_l2"]
    hs = spec["hybrid_study"]
    t, net = spec["training"], spec["network"]
    d = hs["data"]
    seeds = sorted({r["seed"] for r in records})
    L = [
        f"# Step 4.6 hybrid data + physics (Case D) — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_6_hybrid_{tag}/metrics.json)",
        "",
        f"Network {net.get('arch', 'mlp')} {net['depth']}x{net['width']} {net['activation']}, formulation {hs['formulation']}, problem overrides "
        f"{hs.get('problems') or 'none'}, Adam {t['adam']['epochs']} + L-BFGS {t['lbfgs']['iterations']} per network, common {hs.get('common') or 'none'}, "
        f"seeds {seeds}, profile `{spec['profile']}`; each run in its own process. Data = verified solver fields {d['fields']} at {d['placement']} "
        f"fluid cells of the fine reference grid (noise {d['noise']:g} x field RMS, data seed {d['seed']}; sets nested in n), data weight "
        f"{spec['loss']['weights'].get('data', 1.0):g}. Modes: data_free = physics only; hybrid = physics + data; data_only = physics weights 0 "
        "(with exact ψ boundary values the ansatz still imposes the inlet profile and impermeable walls). Worst = max(u, v, θ) rel L2 "
        "(u, v relative to the velocity-vector norm); fit = worst relative misfit on the data points themselves.",
        "",
    ]
    for case in dict.fromkeys(r["case"] for r in records):
        L += [f"## {case}", ""]
        pts = [r for r in records if r["case"] == case and r["kind"] == "per_point"]
        if pts:
            p0 = pts[0]
            cref = next(
                (x for x in refs if x["case"] == case and x["point"] == p0["point"] and x["role"] == "test"), None
            )
            L += [
                f"### One test point (p{p0['point']}, {p0['split']}: Re {p0['Re']:.4g}, Pr {p0['Pr']:.4g}, Bi {p0.get('Bi', float('nan')):.4g}); "
                f"errors on {p0['n_eval_cells']} held-out fluid cells"
                + (f"; reference coarse-fine max(u, v, θ) {p0['ref_unc_max']:.1e}" if cref else ""),
                "",
                "| mode | n data | worst | u | v | θ | p | q err | "
                + ("C_D err | " if any("C_D_rel_err" in r for r in pts) else "")
                + "fit | training s |",
                "|---|---|---|---|---|---|---|---|"
                + ("---|" if any("C_D_rel_err" in r for r in pts) else "")
                + "---|---|",
            ]
            for r in sorted(
                pts, key=lambda r: (["data_free", "data_only", "hybrid"].index(r["mode"]), r["n_data"], r["seed"])
            ):
                L.append(
                    f"| {r['mode']} | {r['n_data']} | {_fmt(r['rel_l2_max'])} | {_fmt(r['rel_l2_u'])} | {_fmt(r['rel_l2_v'])} | "
                    f"{_fmt(r['rel_l2_theta'])} | {_fmt(r['rel_l2_p'])} | {_fmt(r['q_bottom_rel_err'])} | "
                    + (f"{_fmt(r.get('C_D_rel_err'))} | " if any("C_D_rel_err" in x for x in pts) else "")
                    + f"{_fmt(r['data_fit']) if r['data_fit'] is not None else '—'} | {r['train_wall_s']:.0f} |"
                )
            free = [r["rel_l2_max"] for r in pts if r["mode"] == "data_free"]
            e_free = float(np.mean(free)) if free else float("nan")
            ns = sorted({r["n_data"] for r in pts if r["mode"] != "data_free"})

            hyb = {n: _mode_mean(pts, "hybrid", n) for n in ns}
            only = {n: _mode_mean(pts, "data_only", n) for n in ns}
            L.append("")
            if any(np.isfinite(v) for v in hyb.values()):
                n_tgt = _first_n(ns, [hyb[n] < tgt for n in ns])
                n_free = _first_n(ns, [hyb[n] * EFFECT <= e_free for n in ns]) if np.isfinite(e_free) else None
                n_only = _first_n(ns, [np.isfinite(only[n]) and hyb[n] * EFFECT <= only[n] for n in ns])
                L.append(
                    f"How little data suffices (hybrid, n in {ns}): target rel L2 < {tgt:g} from n = {n_tgt if n_tgt else 'none'}; "
                    f"≥{EFFECT:g}x better than data_free ({_fmt(e_free)}) from n = {n_free if n_free else 'none'}; "
                    f"≥{EFFECT:g}x better than data_only at the same n from n = {n_only if n_only else 'none'}."
                )
                L.append(
                    "hybrid ÷ data_free per n: "
                    + ", ".join(f"n={n} {hyb[n] / e_free:.2f}" for n in ns if np.isfinite(e_free))
                    + "; hybrid ÷ data_only per n: "
                    + ", ".join(f"n={n} {hyb[n] / only[n]:.2f}" for n in ns if np.isfinite(only[n]))
                    + " (< 1 = hybrid better)."
                )
            for mode in ("data_free", "data_only", "hybrid"):
                e = [r["rel_l2_max"] for r in pts if r["mode"] == mode]
                if e and sum(x >= NOT_CAPTURED for x in e) >= 0.75 * len(e):
                    L.append(
                        f"{mode}: {sum(x >= NOT_CAPTURED for x in e)}/{len(e)} errors ≥ {NOT_CAPTURED:g} — solution not captured."
                    )
            L.append("")
        par = [r for r in records if r["case"] == case and r["kind"] == "parametric"]
        if par:
            modes = list(dict.fromkeys(r["mode"] for r in par))
            snap = next((r for r in par if r["mode"] != "data_free"), None)
            L += [
                "### Parametric network (one network over the parameter box)"
                + (
                    f"; data = {snap['n_snapshots']} snapshots at TRAIN design points x {snap['n_data']} cells"
                    if snap
                    else ""
                ),
                "",
                "| point | split | Pe | "
                + " | ".join(f"{m} worst" for m in modes)
                + " | "
                + " | ".join(f"{m} q err" for m in modes)
                + " |",
                "|---|---|---|" + "---|" * (2 * len(modes)),
            ]
            for p in sorted({r["point"] for r in par}):
                rs = {r["mode"]: r for r in par if r["point"] == p}
                any_r = next(iter(rs.values()))
                L.append(
                    f"| {p} | {any_r['split']} | {any_r['Pe']:.4g} | "
                    + " | ".join(_fmt(rs[m]["rel_l2_max"]) if m in rs else "—" for m in modes)
                    + " | "
                    + " | ".join(_fmt(rs[m]["q_bottom_rel_err"]) if m in rs else "—" for m in modes)
                    + " |"
                )
            L.append("")
            for m in modes:
                for split in ("interp", "extrap"):
                    e = [r["rel_l2_max"] for r in par if r["mode"] == m and r["split"] == split]
                    if e:
                        L.append(f"- {m} {split}: mean {_fmt(float(np.mean(e)))}, max {_fmt(max(e))}.")
            if "hybrid" in modes and "data_free" in modes:
                rat = {
                    p: next(r["rel_l2_max"] for r in par if r["mode"] == "hybrid" and r["point"] == p)
                    / next(r["rel_l2_max"] for r in par if r["mode"] == "data_free" and r["point"] == p)
                    for p in sorted({r["point"] for r in par})
                }
                better = [p for p, v in rat.items() if v * EFFECT <= 1]
                worse = [p for p, v in rat.items() if v >= EFFECT]
                L.append(
                    "hybrid ÷ data_free per point: "
                    + ", ".join(f"p{p} {v:.2f}" for p, v in rat.items())
                    + f"; ≥{EFFECT:g}x better at {better or 'none'}; ≥{EFFECT:g}x worse at {worse or 'none'}."
                )
            for m in modes:
                e = [r["rel_l2_max"] for r in par if r["mode"] == m]
                if sum(x >= NOT_CAPTURED for x in e) >= 0.75 * len(e):
                    L.append(
                        f"{m}: {sum(x >= NOT_CAPTURED for x in e)}/{len(e)} errors ≥ {NOT_CAPTURED:g} — solution not captured."
                    )
            L.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


def _ms(v: list[float]) -> tuple[float, float]:
    """Mean and sample standard deviation (nan for fewer than 2 values)."""
    if not v:
        return float("nan"), float("nan")
    return float(np.mean(v)), float(np.std(v, ddof=1)) if len(v) > 1 else float("nan")


def ablation_aggregate(records: list[dict]) -> dict[str, dict]:
    """Per configuration, over seeds: the run error (parametric: mean worst-field rel L2 over the interp test points;
    per point: the worst-field rel L2), the extrapolation error (parametric: mean over the extrap points), the
    bottom-wall heat-flux error (mean over the scored points) and the training time; mean and sample std."""
    out: dict[str, dict] = {}
    for name in dict.fromkeys(r["config"] for r in records):
        rs = [r for r in records if r["config"] == name]
        seeds = sorted({r["seed"] for r in rs})
        err, ext, q, tm = [], [], [], []
        for s in seeds:
            rr = [r for r in rs if r["seed"] == s]
            inter = [r for r in rr if r["kind"] == "per_point" or r["split"] == "interp"]
            err.append(float(np.mean([r["rel_l2_max"] for r in inter])))
            ex = [r["rel_l2_max"] for r in rr if r["kind"] == "parametric" and r["split"] == "extrap"]
            if ex:
                ext.append(float(np.mean(ex)))
            q.append(float(np.mean([r["q_bottom_rel_err"] for r in inter])))
            tm.append(float(rr[0]["train_wall_s"]))
        g = {
            "design": rs[0]["design"],
            "changed": rs[0]["changed"],
            "on": rs[0]["components"],
            "seeds": seeds,
            "errs": err,
        }
        for k, v in (("err", err), ("ext", ext), ("q", q), ("time", tm)):
            g[f"{k}_mean"], g[f"{k}_std"] = _ms(v)
        out[name] = g
    return out


def _pm(m: float, s: float, f: str = ".3g") -> str:
    return "—" if not np.isfinite(m) else (format(m, f) + (f" ± {format(s, f)}" if np.isfinite(s) else ""))


def ablation_table(records: list[dict], spec: dict, path: Path, tag: str) -> list[str]:
    """Step 4.7 report. Rules: a component's effect is called only if the ratio of mean errors to the design's reference
    configuration (full / base) is beyond EFFECT AND the mean ± std intervals do not overlap; otherwise 'no effect beyond
    2x' (or 'within the seed spread'). Fewer than 3 seeds are flagged. Mean errors ≥ NOT_CAPTURED are marked."""
    ab = spec["ablation_study"]
    t, net = spec["training"], spec["network"]
    agg = ablation_aggregate(records)
    kind = records[0]["kind"]
    n_seeds = min(len(g["seeds"]) for g in agg.values())
    err_def = (
        "mean worst-field rel L2 over the interp test points (extrap: over the extrap points)"
        if kind == "parametric"
        else f"worst-field rel L2 at test point p{records[0]['point']} on held-out cells"
    )
    L = [
        f"# Step 4.7 ablation — `{tag}` (auto-generated by experiments/p4_report.py from results/p4_7_ablation_{tag}/metrics.json)",
        "",
        f"Case {ab['case']} ({kind}); network {net['depth']}x{net['width']} (arch per configuration), Adam {t['adam']['epochs']} + "
        f"L-BFGS {t['lbfgs']['iterations']} per network; seeds {sorted({r['seed'] for r in records})}; profile `{spec['profile']}`; one process per run "
        f"(execution workers {spec['execution']['workers']}, threads {spec['execution']['threads_per_worker']}: times are comparable within this study only). "
        f"Error = {err_def}; q = bottom-wall heat-flux rel error; ± = sample std over seeds. Components (ON overrides): "
        + "; ".join(f"{k} {v}" for k, v in ab["components"].items())
        + ".",
        "",
    ]
    if n_seeds < 3:
        L += [
            f"**Only {n_seeds} seed(s) per configuration: below the ≥ 3 seeds of the brief; spreads are not established.**",
            "",
        ]
    verdicts: dict[str, dict[str, str]] = {}
    for dsg, ref_name in (("leave_one_out", "full"), ("add_one_in", "base")):
        names = [n for n, g in agg.items() if g["design"] == dsg]
        if not names:
            continue
        ref = agg.get(ref_name)
        L += [
            f"## {dsg.replace('_', '-')} (reference: `{ref_name}`)",
            "",
            "| configuration | components ON | error | extrap error | q err | training s | ratio to reference | verdict |",
            "|---|---|---|---|---|---|---|---|",
        ]
        verdicts[dsg] = {}
        for n in names:
            g = agg[n]
            ratio = g["err_mean"] / ref["err_mean"] if ref and n != ref_name else float("nan")
            sep = ref is not None and abs(g["err_mean"] - ref["err_mean"]) > (g["err_std"] + ref["err_std"])
            v = ""
            if n != ref_name and ref is not None:
                worse, better = ratio >= EFFECT, ratio * EFFECT <= 1
                if (worse or better) and not sep:
                    v = f"≥{EFFECT:g}x but within the seed spread"
                elif dsg == "leave_one_out":
                    v = (
                        "needed: removing it is ≥2x worse"
                        if worse
                        else "harmful in the recipe: removing it is ≥2x better"
                        if better
                        else "no effect beyond 2x"
                    )
                else:
                    v = (
                        "helps alone: ≥2x better than base"
                        if better
                        else "hurts alone: ≥2x worse than base"
                        if worse
                        else "no effect beyond 2x"
                    )
                verdicts[dsg][g["changed"]] = v
            if g["err_mean"] >= NOT_CAPTURED:
                v = (v + "; " if v else "") + "not captured"
            L.append(
                f"| {n} | {', '.join(g['on']) or 'none'} | {_pm(g['err_mean'], g['err_std'])} | {_pm(g['ext_mean'], g['ext_std'])} | "
                f"{_pm(g['q_mean'], g['q_std'])} | {_pm(g['time_mean'], g['time_std'], '.0f')} | {_fmt(ratio, '.2f')} | {v or '—'} |"
            )
        L.append("")
    comps = list(ab["components"])
    if verdicts:
        L.append("Summary per component (leave-one-out | add-one-in):")
        L.append("")
        for c in comps:
            L.append(
                f"- {c}: {verdicts.get('leave_one_out', {}).get(c, '—')} | {verdicts.get('add_one_in', {}).get(c, '—')}"
            )
        L.append("")
    best = min(agg.values(), key=lambda g: g["err_mean"])
    best_name = next(n for n, g in agg.items() if g is best)
    near = [n for n, g in agg.items() if g["err_mean"] <= EFFECT * best["err_mean"]]
    fastest = min(near, key=lambda n: agg[n]["time_mean"])
    L.append(
        f"Best mean error: `{best_name}` {_pm(best['err_mean'], best['err_std'])} ({best['time_mean']:.0f} s). "
        f"Fastest configuration within {EFFECT:g}x of it: `{fastest}` {_pm(agg[fastest]['err_mean'], agg[fastest]['err_std'])} "
        f"({agg[fastest]['time_mean']:.0f} s). Target rel L2 < {spec['evaluation']['target_rel_l2']:g} met by: "
        + (", ".join(n for n, g in agg.items() if g["err_mean"] < spec["evaluation"]["target_rel_l2"]) or "none")
        + "."
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return L
