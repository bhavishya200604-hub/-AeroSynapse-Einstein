"""LaTeX number macros generated from saved metrics (Phase 6B): every number in a paper is a macro whose definition
records where it came from (results/<run>/metrics.json key path and the RESULTS_REGISTRY ID). Regenerated by the
papers' make_numbers.py; 6B.12 REFRESH diffs the regenerated file against the frozen one.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np

from aerosynapse.thermal._home import CODE, THERMAL_TESTS, HOME as ROOT  # noqa: E402, F401
def metrics(run: str) -> dict:
    return json.loads((ROOT / "results" / run / "metrics.json").read_text(encoding="utf-8"))


def sig(x: float, n: int = 3) -> str:
    """n significant figures, plain notation (no exponent for 1e-4 <= |x| < 1e5)."""
    if x == 0:
        return "0"
    if 1 <= abs(x) < 1e5:  # plain digits: 100 with 2 significant figures is "100", not 1e+02
        d = n - 1 - int(np.floor(np.log10(abs(x))))
        t = f"{round(x, d):.{max(d, 0)}f}"
        return t.rstrip("0").rstrip(".") if "." in t else t  # as %g: no trailing zeros
    s = f"{x:.{n}g}"
    if "e" in s:
        m, e = s.split("e")
        return f"\\ensuremath{{{m}\\times 10^{{{int(e)}}}}}"  # valid in text and in math mode
    return s


MINUS = "\\ensuremath{-}"  # a true minus sign, valid in text and in math mode


def signed(x: float, n: int = 3) -> str:
    """+/- and n significant figures; values >= 1000 as whole numbers with thin-space thousands separators."""
    a = abs(x)
    body = f"{a:,.0f}".replace(",", "\\,") if a >= 1000 else sig(a, n)
    return ("+" if x >= 0 else MINUS) + body


def pct(x: float, n: int = 2, signed: bool = False) -> str:
    v = 100 * x
    s = sig(abs(v), n)
    if signed:
        s = ("+" if v >= 0 else MINUS) + s
    return s + "\\,\\%"


REG_ID = re.compile(r"\bR(?:\d|B)[\w.\-]*\w")  # a RESULTS_REGISTRY row id, e.g. R6.2a, R6B.G3e


class Macros:
    def __init__(self) -> None:
        self.items: list[tuple[str, str, str]] = []

    def add(self, name: str, value: str, source: str) -> None:
        """source: what the value is, with the RESULTS_REGISTRY rows it comes from (R...). A macro written right after
        another of the same quantity ('max', 'upper', 'same') inherits that macro's rows, so every macro in
        numbers.tex names its rows (Phase 9 claims audit)."""
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name}")
        if any(n == name for n, _, _ in self.items):
            raise ValueError(f"duplicate macro {name}")
        if not REG_ID.search(source) and self.items:
            prev = REG_ID.findall(self.items[-1][2])
            if prev:
                source = f"{source}; {', '.join(dict.fromkeys(prev))}"
        self.items.append((name, value, source))

    def write(self, path: Path, header: str) -> None:
        L = [f"% {header}", "% AUTO-GENERATED - do not edit; regenerate with the paper's make_numbers.py", ""]
        for n, v, s in self.items:
            L.append(f"\\newcommand{{\\{n}}}{{{v}}}% {s}")
        path.write_text("\n".join(L) + "\n", encoding="utf-8")
