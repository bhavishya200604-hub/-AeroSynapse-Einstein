def _rel(path: str, out_dir: Path) -> str:
    p = ROOT / path
    try:
        return p.relative_to(out_dir).as_posix()
    except ValueError:
        return Path(path).as_posix()


def write(entries: list[dict], out_dir: Path, reel: dict) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    cats = [c for c in CAT if any(e.get("category") == c for e in entries)]
    sections = []
    for c in cats:
        cards = []
        for e in [e for e in entries if e.get("category") == c]:
            f = e["files"]
            prev = f.get("webp") or f.get("gif") or f.get("apng")
            img = (
                f'<img loading="lazy" src="{html.escape(_rel(prev, out_dir))}" alt="{html.escape(e["title"])}">'
                if prev
                else ""
            )
            links = " ".join(
                f'<a href="{html.escape(_rel(v, out_dir))}">{LABEL.get(k, k)}</a>'
                for k, v in f.items()
                if k != "frames"
            )
            cards.append(
                f'<article class="card">{img}<div class="b"><h3>{html.escape(e["title"])}</h3>'
                f'<p>{html.escape(e["caption"])}</p><p class="src">Source: {html.escape(e["source"])}</p>'
                f'<div class="meta">{e["frames"]} frames, {e["seconds"]} s at {e["fps"]} frames/s</div>'
                f'<div class="links">{links}</div></div></article>'
            )
        sections.append(f'<section data-c="{c}"><h2>{CAT[c]}</h2><div class="grid">{"".join(cards)}</div></section>')
    nav = '<button data-c="all" aria-pressed="true">All</button>' + "".join(
        f'<button data-c="{c}" aria-pressed="false">{CAT[c]}</button>' for c in cats
    )
    rl = ""
    if reel and not reel.get("error"):
        parts = [
            f'<a href="{html.escape(_rel(v, out_dir))}">{"video" if k == "mp4" else "PowerPoint deck"}</a>'
            for k, v in reel.items()
        ]
        rl = f'<p class="reel">Showreel of every animation: {" · ".join(parts)}</p>'
    elif reel and reel.get("error"):
        rl = f'<p class="reel">Showreel not built: {html.escape(reel["error"])}</p>'
    out = out_dir / "index.html"
    out.write_text(PAGE.format(reel=rl, nav=nav, sections="".join(sections)), encoding="utf-8")
    return out
