"""Phase 4: neural operators, hybrids, UQ (see aerosynapse.experiments.studies.phase4)."""

from __future__ import annotations

import json

import torch
from _common import RESULTS, parse_profile

from aerosynapse.experiments import ExperimentRecord, ExperimentRun
from aerosynapse.experiments.studies import phase4 as S
from aerosynapse.ml.io import save_model


def main() -> None:
    a = parse_profile(__doc__ or "")
    P = S.PROFILES[a.profile]
    torch.set_num_threads(4)
    rec = ExperimentRecord(
        experiment_id="phase4_operators_uq",
        research_question="How well do FNO/DeepONet and baselines learn the parametric conv-diff solution operator, "
        "generalise to unseen parameters / inputs / resolutions, and how calibrated is their uncertainty?",
        hypothesis="H4.1 FNO beats CNN/MLP/DeepONet in-distribution. H4.2 all models degrade out-of-distribution in "
        "Pe (200-1000) by > 2x. H4.3 FNO error is approximately resolution-independent; CNN is not. "
        "H4.4 the mass-conserving FNO has zero mass error and no worse accuracy. H4.5 ensemble spread under-covers "
        "OOD. H4.6 neural correction of a coarse solver beats both the coarse solver and the pure network. "
        "H4.7 an FNO initial guess reduces CG iterations.",
        mathematical_formulation="G: (u0, Pe) -> u(., T=0.5), u_t + u_x = Pe^-1 u_xx periodic; f -> u for -lap u = f",
        seed=0,
        model_configuration={
            "fno": "width 32, 12 modes, 4 layers",
            "deeponet": "p=64, 3x128",
            "cnn": "4x32 k=5",
            "mlp": "3x256",
            "pod": "rank 16, poly 3",
        },
        training_configuration={"profile": a.profile, **P, "loss": "relative L2", "optimizer": "Adam 1e-3 cosine"},
        dataset_description="synthetic, generated by the FV solver (dataset card in metrics.json)",
        evaluation_metrics=[
            "per-sample rel. L2 distribution",
            "mass error",
            "coverage",
            "NLL",
            "speed-up",
            "break-even queries",
            "CG iterations",
        ],
        reproducibility=f"python scripts/run_phase4.py --profile {a.profile}",
        limitations=["1D/2D synthetic data", "single training seed for point models (ensemble for UQ)"],
    )
    with ExperimentRun(rec, RESULTS) as run:
        ops = S.operators(P)
        models, (tr, te, ood) = ops.pop("_models"), ops.pop("_data")
        save_model(models["fno"][0], run.dir / "fno.pt", {"arch": "FNO1d(2,1,32,12,4)"})
        res = {
            "operators": ops,
            "ensemble_uq": S.ensemble_uq(P, tr, te, ood),
            "multifidelity": S.multifidelity(P),
            "neural_correction": S.neural_correction(P),
            "cg_residual_correction": S.residual_correction_cg(P),
            "classical_uq": S.classical_uq(),
        }
        run.record.results.update(res)
    print(json.dumps(res, indent=1, default=str)[:6000])


if __name__ == "__main__":
    main()
