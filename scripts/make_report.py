"""Generate paper/tables/*.tex and docs/RESULTS_TABLES.md directly from results/ (no hand-typed numbers)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
TAB = ROOT / "paper" / "tables"


def load(e: str) -> dict | None:
    p = RES / e / "metrics.json"
    return json.loads(p.read_text()) if p.exists() else None


def fmt(v: float | None, p: int = 3) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return str(v)
    return f"{v:.{p}g}" if abs(v) < 1e-2 or abs(v) >= 1e3 else f"{v:.{p}f}" if abs(v) < 1 else f"{v:.{p}g}"


def tex_table(name: str, caption: str, header: list[str], rows: list[list[str]]) -> str:
    def esc(x: str) -> str:
        return x.replace("_", r"\_")

    cols = "l" * len(header)
    body = "\n".join(" & ".join(esc(c) for c in r) + r" \\" for r in rows)
    t = (
        f"\\begin{{table}}[t]\\centering\\small\\caption{{{esc(caption)}}}\\label{{tab:{name}}}\n"
        f"\\begin{{tabular}}{{{cols}}}\\toprule\n{' & '.join(esc(h) for h in header)} \\\\ \\midrule\n{body}\n"
        f"\\bottomrule\\end{{tabular}}\\end{{table}}\n"
    )
    src = {
        "phase1": "phase1_verification",
        "phase2": "phase2_pinn_benchmarks",
        "phase4": "phase4_operators_uq",
        "phase5": "phase5_optimization",
    }.get(name, "phase3_adaptive_collocation" if name.startswith("phase3") else "phase6_fluids_aero")
    (TAB / f"{name}.tex").write_text(f"% sources: {src}\n" + t, encoding="utf-8")
    md = [f"### {caption}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(md) + "\n"


def main() -> None:
    TAB.mkdir(parents=True, exist_ok=True)
    out = ["# Results tables (auto-generated by scripts/make_report.py from results/)", ""]
    m1 = load("phase1_verification")
    if m1:
        rows = [
            [k, fmt(v["errors"][-1]), fmt(v["pairwise_orders"][-1])]
            for k, v in m1.items()
            if isinstance(v, dict) and "pairwise_orders" in v
        ]
        out.append(
            tex_table(
                "phase1",
                "Observed order of accuracy (finest pair), Phase 1",
                ["case", "finest error", "observed order"],
                rows,
            )
        )
    m2 = load("phase2_pinn_benchmarks")
    if m2:
        rows = [[k.replace("/None", ""), fmt(v["mean"]), fmt(v["std"]), str(v["n"])] for k, v in m2["pinn"].items()]
        rows += [[f"supervised/{k}", fmt(v["mean"]), fmt(v["std"]), str(v["n"])] for k, v in m2["supervised"].items()]
        out.append(
            tex_table(
                "phase2",
                "PINN and supervised-baseline relative L2 error vs exact solutions",
                ["case/hard BC", "mean", "sd", "seeds"],
                rows,
            )
        )
    m3 = load("phase3_adaptive_collocation")
    if m3:
        rows = []
        for k, v in m3["table"].items():
            pe, meth = k.split("/")
            h = m3["tests"][pe]["holm"].get(meth)
            rows.append(
                [
                    pe,
                    meth,
                    fmt(v["median"]),
                    f"[{fmt(v['ci95'][0])}, {fmt(v['ci95'][1])}]",
                    fmt(h["p_holm"]) if h else "-",
                    ("yes" if h and h["reject"] else "no") if h else "-",
                    fmt(v["wall_s_mean"], 3),
                ]
            )
        out.append(
            tex_table(
                "phase3",
                f"Equal-budget sampler comparison ({m3['seeds']} seeds; paired Wilcoxon vs uniform, Holm within Pe)",
                ["Pe", "sampler", "median rel. L2", "95% CI", "p (Holm)", "significant", "wall s"],
                rows,
            )
        )
        rows = [
            [
                k,
                fmt(v["median"]),
                fmt(v["baseline_median"]),
                fmt(v["p_wilcoxon_vs_baseline"]),
                fmt(v["early_t_median"]),
                fmt(v["baseline_early_t_median"]),
            ]
            for k, v in m3["ablation"].items()
        ]
        out.append(
            tex_table(
                "phase3_ablation",
                "Ablations (paired vs the same sampler without the component)",
                ["ablation/Pe/sampler", "median", "baseline median", "p", "early-t median", "baseline early-t"],
                rows,
            )
        )
    m4 = load("phase4_operators_uq")
    if m4:
        o = m4["operators"]
        rows = [
            [
                k,
                fmt(o[k]["test_id"]["median"]),
                fmt(o[k]["test_id"]["max"]),
                fmt(o[k]["ood_pe"]["median"]),
                fmt(o[k]["ood_input"]["median"]),
            ]
            for k in ("fno", "fno_mass_conserving", "deeponet", "cnn", "mlp", "pod")
        ]
        out.append(
            tex_table(
                "phase4",
                "Operator learning: per-sample rel. L2 (median, worst case) by split",
                ["model", "ID median", "ID max", "OOD-Pe median", "OOD-input median"],
                rows,
            )
        )
    m5 = load("phase5_optimization")
    if m5:
        rows = [
            [
                k,
                v["verdict"],
                fmt(v["method"]["final"]["trusted_f"][0]) if v["method"]["final"] else "n/a",
                fmt(v["baseline_method"]["final"]["trusted_f"][0]) if v["baseline_method"]["final"] else "n/a",
                fmt(v["baseline"]["f"][0]),
            ]
            for k, v in m5["protocol"].items()
        ]
        out.append(
            tex_table(
                "phase5",
                "Engineering optimisation under the 12-step protocol (trusted re-evaluation)",
                ["problem", "verdict", "method f (trusted)", "baseline optimiser f", "baseline design f"],
                rows,
            )
        )
    m6 = load("phase6_fluids_aero")
    if m6:
        rows = [[k, fmt(v["rms_u"]), fmt(v["rms_v"]), str(v["converged"])] for k, v in m6["cavity"].items()]
        out.append(
            tex_table(
                "phase6_cavity",
                "Lid-driven cavity vs Ghia et al. (1982): centre-line RMS differences",
                ["case", "RMS u", "RMS v", "converged"],
                rows,
            )
        )
    (ROOT / "docs" / "RESULTS_TABLES.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(list(TAB.glob('*.tex')))} tables")


if __name__ == "__main__":
    main()
